# Descent test: does a random target R decompose as a sum of <=3 signed Heegner points more often than over a random set of equal size?
import json,sys,random,math
import numpy as np
import cypari2
from sympy.ntheory import sqrt_mod
pari=cypari2.Pari(); pari.allocatemem(10**8)
ptsf,a,b,tag,ntarg,nctrl=sys.argv[1],int(sys.argv[2]),int(sys.argv[3]),sys.argv[4],int(sys.argv[5]),int(sys.argv[6])
def add(P,Q,p):
    if P is None: return Q
    if Q is None: return P
    x1,y1=P;x2,y2=Q
    if x1==x2:
        if (y1+y2)%p==0: return None
        l=(3*x1*x1+a)*pow(2*y1,-1,p)%p
    else: l=(y2-y1)*pow(x2-x1,-1,p)%p
    x3=(l*l-x1-x2)%p; return (x3,(l*(x1-x3)-y1)%p)
def neg(P,p): return None if P is None else (P[0],(-P[1])%p)
def mul(k,P,p):
    R=None
    while k:
        if k&1: R=add(R,P,p)
        P=add(P,P,p); k>>=1
    return R
def randpt(p,rng):
    while True:
        x=rng.randrange(p); r=(x**3+a*x+b)%p
        if r==0: continue
        y=sqrt_mod(r,p)
        if y is not None: return (x,y if rng.random()<.5 else p-y)
def hits(S,targets,p):
    """boolean list: target = sum of <=3 elements of +-S (repeats allowed)"""
    pm=list(S)+[neg(q,p) for q in S]
    one=[None]+pm
    T=set()
    for i,P in enumerate(one):
        for Q in one[i:]: T.add(add(P,Q,p))     # all sums of <=2 terms (incl. O)
    out=[]
    for R in targets:
        ok=False
        for s in one:
            if add(R,neg(s,p),p) in T: ok=True;break
        out.append(ok)
    return np.array(out)
data=json.load(open(ptsf)); res=[]
for ps,lev in data.items():
    p=int(ps); rng=random.Random(p)
    S=sorted(set(tuple(q) for v in lev.values() for q in v)); N=len(S)
    S=[tuple(q) for q in S]
    ec=pari(f'ellinit([{a},{b}],{p})'); card=int(pari.ellcard(ec)); grp=[int(x) for x in pari.ellgroup(ec)]
    # order of the subgroup generated by S (E(F_p) cyclic or not: use lcm of point orders as a lower bound for the exponent of <S>)
    ords=[int(pari.ellorder(ec,[pari(q[0]),pari(q[1])],card)) if False else int(pari('ellorder')(ec,[pari(f'Mod({q[0]},{p})'),pari(f'Mod({q[1]},{p})')],card)) for q in S]
    expS=math.lcm(*ords)
    targets=[randpt(p,rng) for _ in range(ntarg)]
    h=hits(S,targets,p)
    # control A: N random points of E(F_p)
    ca=[]
    for c in range(nctrl):
        Sc=[randpt(p,rng) for _ in range(N)]
        ca.append(hits(Sc,targets,p))
    ca=np.array(ca)
    # control B + targets restricted to <S>: random elements of <S> (random combinations of 6 elements of S)
    def rand_in_S():
        P=None
        for _ in range(6): P=add(P,mul(rng.randrange(1,p),rng.choice(S),p),p)
        return P if P is not None else S[0]
    tS=[rand_in_S() for _ in range(ntarg)]
    hS=hits(S,tS,p)
    cb=np.array([hits([rand_in_S() for _ in range(N)],tS,p) for _ in range(nctrl)])
    r={'p':p,'#E':card,'group':grp,'N':N,'exp_of_span':expS,'span_index_lower_bound':card//expS if card%expS==0 else None,
       'targets_E':{'heegner_rate':float(h.mean()),'control_mean':float(ca.mean()),'control_sd_over_sets':float(ca.mean(1).std()),'control_min_max':[float(ca.mean(1).min()),float(ca.mean(1).max())],
                    'frac_controls_ge_heegner':float((ca.mean(1)>=h.mean()).mean())},
       'targets_span':{'heegner_rate':float(hS.mean()),'control_mean':float(cb.mean()),'control_sd_over_sets':float(cb.mean(1).std()),'control_min_max':[float(cb.mean(1).min()),float(cb.mean(1).max())],
                    'frac_controls_ge_heegner':float((cb.mean(1)>=hS.mean()).mean())}}
    # paired bootstrap over targets of (heegner - mean control)
    for key,hh,cc in (('targets_E',h,ca),('targets_span',hS,cb)):
        d=hh.astype(float)-cc.mean(0)
        bs=[d[rng.choices(range(ntarg),k=ntarg)].mean() for _ in range(2000)]
        r[key]['diff']=float(d.mean()); r[key]['diff_ci95']=[float(np.percentile(bs,2.5)),float(np.percentile(bs,97.5))]
    res.append(r); print(json.dumps(r),flush=True)
    r['_h']=h.tolist(); r['_hS']=hS.tolist(); r['_ca']=ca.mean(0).tolist(); r['_cb']=cb.mean(0).tolist()
# pooled over primes
H=np.concatenate([np.array(r['_h']) for r in res]).astype(float); C=np.concatenate([np.array(r['_ca']) for r in res])
HS=np.concatenate([np.array(r['_hS']) for r in res]).astype(float); CS=np.concatenate([np.array(r['_cb']) for r in res])
rng=np.random.default_rng(1); pooled={}
for key,hh,cc in (('targets_E',H,C),('targets_span',HS,CS)):
    d=hh-cc; bs=[d[rng.integers(0,len(d),len(d))].mean() for _ in range(5000)]
    pooled[key]={'n_targets':len(d),'heegner_rate':float(hh.mean()),'control_rate':float(cc.mean()),'diff':float(d.mean()),'diff_ci95':[float(np.percentile(bs,2.5)),float(np.percentile(bs,97.5))]}
print('POOLED',json.dumps(pooled))
for r in res: [r.pop(k) for k in ('_h','_hS','_ca','_cb')]
json.dump({'per_prime':res,'pooled':pooled,'params':{'targets':ntarg,'controls':nctrl}},open(f'descent_{tag}.json','w'),indent=1)
