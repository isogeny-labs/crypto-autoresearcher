# Newton polytopes (small variables) of Edwards S_3, S_4 (SA-19 integer form) and Weierstrass controls; JM-centroid reach.
import cypari2, json, math, itertools, numpy as np
from scipy.spatial import ConvexHull, Delaunay
pari=cypari2.Pari(); pari.allocatemem(800*10**6)
def E3(u,v,w): return f"({u}^2*{v}^2*{w}^2-({u}^2*{v}^2+{u}^2*{w}^2+{v}^2*{w}^2)+2*({u}^2+{v}^2+{w}^2)-2*{u}*{v}*{w}-2)"
def W3(u,v,w,A=3,B=5): return f"(({u}-{v})^2*{w}^2-2*(({u}+{v})*({u}*{v}+{A})+2*{B})*{w}+({u}*{v}-{A})^2-4*{B}*({u}+{v}))"
def support(poly, vs):
    res={}
    def rec(q,vs_,ex):
        if not vs_: res[tuple(ex)]=int(q); return
        v=vs_[0]; d=int(pari.poldegree(q,v))
        for e in range(d+1):
            c=pari.polcoef(q,e,v)
            if c!=0: rec(c,vs_[1:],ex+[e])
    rec(pari(poly),vs,[]); return res
def stats(pts):
    pts=np.array(pts,float); pts=pts-pts.min(0); n=pts.shape[1]
    u=np.unique(pts,axis=0); h=u[ConvexHull(u).vertices]; tri=Delaunay(h)
    vol=0; cen=np.zeros(n)
    for s in tri.simplices:
        V=h[s]; v=abs(np.linalg.det(V[1:]-V[0]))/math.factorial(n); vol+=v; cen+=v*V.mean(0)
    return vol,cen/vol,pts.max(0)
out={}
for model,S3f,R in (("edwards",E3,"y4"),("weier",W3,"x4")):
    vs=['a','b','c'] if False else None
    # m=2
    tv=['u1','u2']; r=7
    sup=support(S3f('u1','u2',str(r)),tv)
    # m=3
    t3=['u1','u2','u3']
    S4=pari.polresultant(pari(S3f('u1','u2','Y')),pari(S3f('u3',str(r),'Y')),'Y')
    sup4=support(S4,t3)
    for m,sp in ((2,sup),(3,sup4)):
        pts=list(sp.keys()); vol,g,mx=stats(pts)
        d=1/((m+1)*g.sum())
        par=sorted(set(tuple(e%2 for e in p) for p in pts))
        # sublattice generated by support differences: index in Z^m via Smith/HNF
        P=np.array(pts); D=(P-P[0]).T
        import sympy; from sympy.matrices.normalforms import smith_normal_form
        M=sympy.Matrix(D.tolist()); snf=smith_normal_form(M,domain=sympy.ZZ)
        diag=[abs(snf[i,i]) for i in range(min(snf.shape)) if snf[i,i]!=0]
        idx=int(np.prod(diag)) if len(diag)==m else 0
        rec=dict(model=model,m=m,monos=len(pts),box=int(np.prod(mx+1)),vol_over_box=round(vol/np.prod(mx),4),centroid=g.tolist(),sum_g=float(g.sum()),delta_JM=d,inv=1/d,parity_classes=[list(x) for x in par],sublattice_index=idx,max_exp=mx.tolist(),support=pts)
        out[f"{model}_m{m}"]=rec
        print(model,m,"monos",len(pts),"/",rec['box'],"vol/box",rec['vol_over_box'],"sum_g",round(float(g.sum()),4),"delta",round(d,5),"=1/",round(1/d,3),"parity",par,"sublattice idx",idx,flush=True)
json.dump(out,open("results/step1_polytope.json","w"))
