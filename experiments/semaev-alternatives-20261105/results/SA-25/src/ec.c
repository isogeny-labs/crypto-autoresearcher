// EC arithmetic on E11: y^2 + y = x^3 - x^2 - 10x - 20 over F_p (p < 2^31), plus relation checks, BSGS, rho, linear algebra mod n.
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
typedef int64_t i64; typedef uint64_t u64; typedef struct { i64 x, y; int inf; } pt;
static i64 P_;
static inline i64 md(i64 a){ a%=P_; return a<0?a+P_:a; }
static i64 inv(i64 a){ i64 t=0,nt=1,r=P_,nr=md(a); while(nr){ i64 q=r/nr, tmp=t-q*nt; t=nt; nt=tmp; tmp=r-q*nr; r=nr; nr=tmp; } return t<0?t+P_:t; }
static inline pt add(pt A, pt B){
  if(A.inf) return B; if(B.inf) return A;
  i64 lam;
  if(A.x==B.x){
    if(md(A.y+B.y+1)==0){ pt o={0,0,1}; return o; }
    lam = md(md(3*A.x%P_*A.x - 2*A.x - 10) * inv(2*A.y+1));
  } else lam = md((B.y-A.y) * inv(B.x-A.x));
  i64 x3 = md(lam*lam%P_ + 1 - A.x - B.x);
  i64 y3 = md(-lam*x3%P_ - (A.y - lam*A.x%P_) - 1);
  pt R={x3,y3,0}; return R;
}
static inline pt neg(pt A){ if(!A.inf) A.y = md(-A.y-1); return A; }
static pt smul(pt A, i64 k){ pt R={0,0,1}; if(k<0){ A=neg(A); k=-k; } while(k){ if(k&1) R=add(R,A); k>>=1; if(k) A=add(A,A); } return R; }
void ec_setp(i64 p){ P_=p; }
int ec_oncurve(i64 x,i64 y){ i64 l=md(y*y%P_+y), r=md(((x*x%P_*x - x*x%P_ - 10*x - 20)%P_)); return l==r; }
// relation check: sum coef_i * pt[idx_i] == const (0: O, 1: (16,-61)). out[r]=1 if holds
void ec_verify(i64 p,const i64*X,const i64*Y,i64 nrel,const i64*off,const i64*idx,const i64*coef,const int*cst,int*out){
  P_=p; pt c0={16,md(-61),0};
  for(i64 r=0;r<nrel;r++){
    pt S={0,0,1};
    for(i64 k=off[r];k<off[r+1];k++){ pt Pt={X[idx[k]],Y[idx[k]],0}; S=add(S,smul(Pt,coef[k])); }
    pt T = cst[r]? c0 : (pt){0,0,1};
    out[r] = (S.inf&&T.inf) || (!S.inf&&!T.inf&&S.x==T.x&&S.y==T.y);
  }
}
// multiply many points by k and report whether result is O (n-component zero test) -> out=1 if [k]P==O
void ec_mul_isO(i64 p,const i64*X,const i64*Y,i64 n,i64 k,int*out){ P_=p; for(i64 i=0;i<n;i++){ pt A={X[i],Y[i],0}; out[i]=smul(A,k).inf; } }
// scalar mult of one point
void ec_smul1(i64 p,i64 x,i64 y,i64 k,i64*ox,i64*oy,int*oinf){ P_=p; pt A={x,y,0}; pt R=smul(A,k); *ox=R.x;*oy=R.y;*oinf=R.inf; }
// BSGS logs in cyclic group of prime order n generated by G (affine). pts already in n-component (inf allowed). out[i]=log or -1
typedef struct { i64 x,y; i64 val; } ent;
void ec_bsgs(i64 p,i64 n,i64 gx,i64 gy,const i64*X,const i64*Y,const int*inf,i64 np,i64*out){
  P_=p; pt G={gx,gy,0}; i64 m=1; while(m*m<n) m++;
  i64 H=1; while(H<2*m) H<<=1; ent*tab=calloc(H,sizeof(ent)); for(i64 i=0;i<H;i++) tab[i].val=-1;
  pt cur={0,0,1};
  // baby: j*G for j=0..m-1 ; store (point)->j ; inf stored separately as j=0
  for(i64 j=1;j<m;j++){ cur=add(cur,G); u64 h=((u64)cur.x*1000003ULL+(u64)cur.y*911ULL)&(H-1); while(tab[h].val>=0) h=(h+1)&(H-1); tab[h].x=cur.x; tab[h].y=cur.y; tab[h].val=j; }
  pt mG=add(cur,G); pt nmG=neg(mG); // m*G
  for(i64 i=0;i<np;i++){
    pt Q={X[i],Y[i],inf[i]}; out[i]=-1;
    for(i64 g=0; g<=m+1; g++){
      if(Q.inf){ out[i]=(g*m)%n; break; }
      u64 h=((u64)Q.x*1000003ULL+(u64)Q.y*911ULL)&(H-1); int f=0;
      while(tab[h].val>=0){ if(tab[h].x==Q.x&&tab[h].y==Q.y){ out[i]=(g*m+tab[h].val)%n; f=1; break;} h=(h+1)&(H-1); }
      if(f) break; Q=add(Q,nmG);
    }
  }
  free(tab);
}
// ---- linear algebra mod n (n < 2^31): rank + kernel of sparse rows
static inline u64 mulm(u64 a,u64 b,u64 n){ return a*b%n; }
static u64 powm(u64 a,u64 e,u64 n){ u64 r=1; a%=n; while(e){ if(e&1) r=r*a%n; a=a*a%n; e>>=1;} return r; }
// rows in CSR over ncols columns (coef mod n). Returns rank. If kern!=NULL (size (ncols-rank)*ncols filled), writes kernel basis rows.
i64 la_rank_kernel(i64 n,i64 ncols,i64 nrows,const i64*off,const i64*col,const i64*val,i64*kern){
  // compress to touched columns
  int*touched=calloc(ncols,sizeof(int)); for(i64 k=0;k<off[nrows];k++) touched[col[k]]=1;
  i64*cmap=malloc(ncols*sizeof(i64)); i64 tc=0; for(i64 c=0;c<ncols;c++) cmap[c]= touched[c]? tc++ : -1;
  i64 cap = nrows<tc? nrows:tc; u64*M=calloc((size_t)(cap>0?cap:1)*(tc>0?tc:1),sizeof(u64)); i64*pc=malloc((cap>0?cap:1)*sizeof(i64)); i64 rk=0;
  u64*v=malloc((tc>0?tc:1)*sizeof(u64));
  for(i64 r=0;r<nrows && rk<tc;r++){
    memset(v,0,tc*sizeof(u64)); for(i64 k=off[r];k<off[r+1];k++){ i64 c=cmap[col[k]]; v[c]=(v[c]+(u64)(((val[k]%n)+n)%n))%n; }
    for(i64 q=0;q<rk;q++){ u64 f=v[pc[q]]; if(f){ u64 nf=n-f; u64*row=M+(size_t)q*tc; for(i64 c=0;c<tc;c++) if(row[c]) v[c]=(v[c]+nf*row[c])%n; } }
    i64 piv=-1; for(i64 c=0;c<tc;c++) if(v[c]){ piv=c; break; }
    if(piv<0) continue;
    u64 iv=powm(v[piv],n-2,n); u64*row=M+(size_t)rk*tc; for(i64 c=0;c<tc;c++) row[c]=v[c]*iv%n; pc[rk]=piv; rk++;
  }
  i64 rank=rk;
  if(kern){
    // back-substitute to RREF
    for(i64 q=rk-1;q>=0;q--) for(i64 q2=0;q2<q;q2++){ u64*r2=M+(size_t)q2*tc; u64 f=r2[pc[q]]; if(f){ u64 nf=n-f; u64*rq=M+(size_t)q*tc; for(i64 c=0;c<tc;c++) if(rq[c]) r2[c]=(r2[c]+nf*rq[c])%n; } }
    int*ispiv=calloc(tc>0?tc:1,sizeof(int)); for(i64 q=0;q<rk;q++) ispiv[pc[q]]=1;
    i64*rev=malloc((tc>0?tc:1)*sizeof(i64)); for(i64 c=0;c<ncols;c++) if(cmap[c]>=0) rev[cmap[c]]=c;
    i64 kk=0; memset(kern,0,(size_t)(ncols-rank)*ncols*sizeof(i64));
    for(i64 c=0;c<ncols;c++){
      if(cmap[c]<0){ kern[kk*ncols+c]=1; kk++; }
      else if(!ispiv[cmap[c]]){ i64*kr=kern+kk*ncols; kr[c]=1; for(i64 q=0;q<rk;q++){ u64 a=M[(size_t)q*tc+cmap[c]]; if(a) kr[rev[pc[q]]]=(i64)((n-a)%n); } kk++; }
    }
    free(ispiv); free(rev);
  }
  free(touched);free(cmap);free(M);free(pc);free(v); return rank;
}

void ec_mulvec(i64 p,const i64*X,const i64*Y,i64 n,i64 k,i64*OX,i64*OY,int*Oinf){ P_=p; for(i64 i=0;i<n;i++){ pt A={X[i],Y[i],0}; pt R=smul(A,k); OX[i]=R.x;OY[i]=R.y;Oinf[i]=R.inf; } }
static u64 rs;
static inline u64 rnd(void){ rs^=rs<<13; rs^=rs>>7; rs^=rs<<17; return rs; }
static inline double now(void){ struct timespec t; clock_gettime(CLOCK_MONOTONIC,&t); return t.tv_sec+1e-9*t.tv_nsec; }
// Connection walk. Steps S_m = a_m P + b_m Q + T_m (T_m in cofactor subgroup). R += S_rand each trial.
// Class lookup: hash of class points (cx,cy) -> local index. Collect up to maxhits hits: (local idx, a, b). Returns trials; secs out.
i64 ec_connect(i64 p,i64 n,i64 Px,i64 Py,i64 Qx,i64 Qy,const i64*Tx,const i64*Ty,const int*Tinf,i64 nT,
               const i64*cx,const i64*cy,i64 nc,i64 maxhits,i64 maxtrials,u64 seed,i64*hidx,i64*ha,i64*hb,i64*nhits,double*secs){
  double t0=now(); P_=p; rs=seed*0x9E3779B97F4A7C15ULL+88172645463325252ULL; for(int i=0;i<10;i++) rnd();
  i64 H=1; while(H<4*nc+4) H<<=1; i64*tab=malloc(H*sizeof(i64)); for(i64 i=0;i<H;i++) tab[i]=-1;
  for(i64 i=0;i<nc;i++){ u64 h=((u64)cx[i]*1000003ULL+(u64)cy[i]*911ULL)&(H-1); while(tab[h]>=0) h=(h+1)&(H-1); tab[h]=i; }
  pt P={Px,Py,0}, Q={Qx,Qy,0}; enum{NS=32}; pt S[NS]; i64 sa[NS],sb[NS];
  for(int m=0;m<NS;m++){ sa[m]=rnd()%n; sb[m]=rnd()%n; pt t=add(smul(P,sa[m]),smul(Q,sb[m])); if(nT>0){ i64 ti=rnd()%nT; pt T={Tx[ti],Ty[ti],Tinf[ti]}; t=add(t,T);} S[m]=t; }
  i64 a=rnd()%n,b=rnd()%n; pt R=add(smul(P,a),smul(Q,b)); if(nT>0){ i64 ti=rnd()%nT; pt T={Tx[ti],Ty[ti],Tinf[ti]}; R=add(R,T);} 
  i64 trials=0,nh=0;
  while(nh<maxhits && trials<maxtrials){
    int m=rnd()%NS; R=add(R,S[m]); a+=sa[m]; if(a>=n)a-=n; b+=sb[m]; if(b>=n)b-=n; trials++;
    if(R.inf) continue;
    u64 h=((u64)R.x*1000003ULL+(u64)R.y*911ULL)&(H-1);
    while(tab[h]>=0){ i64 i=tab[h]; if(cx[i]==R.x&&cy[i]==R.y){ hidx[nh]=i; ha[nh]=a; hb[nh]=b; nh++; break; } h=(h+1)&(H-1); }
  }
  *secs=now()-t0; *nhits=nh; free(tab); return trials;
}
// Rho with distinguished points, single process. Solve Q=kP in group of prime order n. Returns k or -1; adds counted.
i64 ec_rho(i64 p,i64 n,i64 Px,i64 Py,i64 Qx,i64 Qy,u64 seed,int dpbits,i64 maxadds,i64*adds,double*secs){
  double t0=now(); P_=p; rs=seed*0x9E3779B97F4A7C15ULL+1234567ULL; for(int i=0;i<10;i++) rnd();
  pt P={Px,Py,0},Q={Qx,Qy,0}; enum{NS=32}; pt S[NS]; i64 sa[NS],sb[NS];
  for(int m=0;m<NS;m++){ sa[m]=1+rnd()%(n-1); sb[m]=1+rnd()%(n-1); S[m]=add(smul(P,sa[m]),smul(Q,sb[m])); }
  i64 H=1<<14; typedef struct{ i64 x,y,a,b; int used; } dpe; dpe*tab=calloc(H,sizeof(dpe));
  i64 na=0; i64 mask=(1LL<<dpbits)-1; i64 ans=-1; i64 ndp=0;
  while(na<maxadds && ans<0 && ndp<H/2){
    i64 a=rnd()%n,b=rnd()%n; pt R=add(smul(P,a),smul(Q,b)); na+=2; i64 len=0;
    while(len<(mask+1)*30 && na<maxadds){
      if(!R.inf && (R.x&mask)==0) {
        u64 h=((u64)R.x*1000003ULL+(u64)R.y*911ULL)&(H-1); int dup=0;
        while(tab[h].used){ if(tab[h].x==R.x&&tab[h].y==R.y){ dup=1; break;} h=(h+1)&(H-1); }
        if(dup){ i64 da=(a-tab[h].a)%n; if(da<0)da+=n; i64 db=(tab[h].b-b)%n; if(db<0)db+=n; // a P + b Q = a' P + b' Q -> (a-a')P=(b'-b)Q = (b'-b)kP
          if(db!=0){ // k = da/db
            u64 e=n-2, base=db, r=1; while(e){ if(e&1) r=r*base%n; base=base*base%n; e>>=1; } ans=(i64)(((u64)da*r)%n); }
          break; }
        tab[h].used=1; tab[h].x=R.x; tab[h].y=R.y; tab[h].a=a; tab[h].b=b; ndp++; break;
      }
      if(R.inf){ break; }
      int m=(int)((((u64)R.x*2654435761ULL)>>7)%NS); R=add(R,S[m]); a+=sa[m]; if(a>=n)a-=n; b+=sb[m]; if(b>=n)b-=n; na++; len++;
    }
  }
  *secs=now()-t0; *adds=na; free(tab); return ans;
}
