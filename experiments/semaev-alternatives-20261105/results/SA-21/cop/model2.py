"""Exact MILP shift-set certifier with the EXACT (sparse) support of f and an optional lattice-coset restriction.
Lattice rows p^{t-k} y^s f^k (k=0..t), leading monomial s+k*lam, monomial set M arbitrary (not forced down-closed).
Gain(M)=sum_{y in M}(level(y)-cost(y)) > 0  <=> det < p^{t|M|} (Howgrave-Graham/LLL asymptotic condition), cost(y)=sum_j e_j y_j.
Level(y)=max k s.t. s=y-k*lam>=0 and s+kfold(S) subset M.  One row per y (sum_k v<=z_y).
Cosets: y restricted to a single coset of the sublattice Lam generated by S-S (coset = tuple of (y_j - y_0) mod 2, j>=1, for the 'all exponents congruent mod 2' lattice)."""
import numpy as np, itertools, scipy.sparse as sps
from scipy.optimize import milp, LinearConstraint, Bounds
def kfold(S,k,cache):
    if k in cache: return cache[k]
    if k==0: r={tuple([0]*len(S[0]))}
    else:
        prev=kfold(S,k-1,cache); r={tuple(a+b for a,b in zip(p,q)) for p in prev for q in S}
    cache[k]=r; return r
class Model2:
    def __init__(self,S,lam,t,coset=None):
        S=[tuple(s) for s in S]; n=len(S[0]); self.n=n; self.t=t
        ext=[t*max(s[j] for s in S) for j in range(n)]
        cache={}
        def incoset(y):
            if coset is None: return True
            return all((y[j]-y[0]-coset[j-1])%2==0 for j in range(1,n))
        # coset test: all coordinates congruent to coset vector mod 2 (valid for parity-lattice supports)
        pts=[y for y in itertools.product(*[range(e+1) for e in ext]) if incoset(y)]
        self.pts=pts; idx={y:i for i,y in enumerate(pts)}; nz=len(pts); self.nz=nz
        vl=[]
        for y in pts:
            for k in range(1,t+1):
                s=tuple(y[j]-k*lam[j] for j in range(n))
                if min(s)<0: break
                cps=[tuple(s[j]+c[j] for j in range(n)) for c in kfold(S,k,cache)]
                if any(cp not in idx for cp in cps): continue
                vl.append((idx[y],k,[idx[cp] for cp in cps]))
        self.vl=vl; nv=len(vl); N=nz+nv; self.N=N
        rows=[];cols=[];vals=[];ri=0
        for q,(yi,k,cl) in enumerate(vl):
            for cp in cl: rows+=[ri,ri];cols+=[nz+q,cp];vals+=[1,-1];ri+=1
        byy={}
        for q,(yi,k,cl) in enumerate(vl): byy.setdefault(yi,[]).append(q)
        for yi,qs in byy.items():
            for q in qs: rows.append(ri);cols.append(nz+q);vals.append(1)
            rows.append(ri);cols.append(yi);vals.append(-1);ri+=1
        self.A=sps.csr_matrix((vals,(rows,cols)),shape=(ri,N)); self.nrows=ri
        self.lev=np.array([v[1] for v in vl],float)
        self.P=np.array(pts,float)
    def milp_gain(self,cost,tl=60):
        cz=self.P@np.array(cost,float)
        obj=np.concatenate([cz,-self.lev])
        res=milp(obj,constraints=LinearConstraint(self.A,-np.inf,0),integrality=np.ones(self.N),bounds=Bounds(0,1),options=dict(time_limit=tl,mip_rel_gap=1e-6))
        if res.x is None: return None,None
        return -res.fun,getattr(res,'mip_dual_bound',None)
def reach(model,costfn,lo=0.0,hi=0.3,tol=5e-4,tl=60):
    gaps=[]
    for _ in range(30):
        mid=(lo+hi)/2
        g,db=model.milp_gain(costfn(mid),tl)
        if g is not None and g>1e-7: lo=mid
        else: hi=mid
        if hi-lo<tol: break
    return lo
