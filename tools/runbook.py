def load_session(repo: Path, session: str | Path) -> tuple[Path, list[dict[str, Any]], Runbook]:
    repo = repo.resolve()
    path = Path(session)
    path = (path if path.is_absolute() else repo / path).resolve()
    journal = path / "journal.jsonl"
    if not journal.is_file():
        raise RunbookError(f"{rel(repo, path) if repo in path.parents else path}: no journal.jsonl")
    entries = read_journal(journal)
    if not entries or entries[0].get("type") != "session_started":
        raise RunbookError("journal does not begin with session_started")
    runbook = load_runbook(repo, entries[0]["runbook"])
    return path, entries, runbook


def verify(repo: Path, session: str | Path, *, rerun_checks: bool = False) -> list[str]:
    path, entries, runbook = load_session(repo, session)
    repo = repo.resolve()
    out = chain_findings(entries)
    start = entries[0]
    if start.get("runbook_sha256") != runbook.sha256:
        out.append(f"{runbook.path} has changed since the session started")
    if rel(repo, path) != runbook.session_dir:
        out.append(f"session directory is not {runbook.session_dir}")
    for bind in start.get("binds") or []:
        try:
            if sha256_file(resolve(repo, bind["path"])) != bind["sha256"]:
                out.append(f"bound file {bind['path']} has changed")
        except (OSError, RunbookError):
            out.append(f"bound file {bind['path']} is missing")
    finished = [e for e in entries if e["type"] == "session_finished"]
    if not finished or entries[-1]["type"] != "session_finished":
        out.append("the session has not finished (no final session_finished entry)")
    recorded: set[str] = {"journal.jsonl"}
    for entry in entries:
        if entry["type"] not in ("step_finished", "step_interrupted"):
            continue
        for item in [*entry.get("outputs", []), *entry.get("logs", [])]:
            file = resolve(repo, item["path"])
            recorded.add(rel(repo, file))
            if not file.is_file():
                out.append(f"{item['path']} is recorded but missing")
            elif sha256_file(file) != item["sha256"]:
                out.append(f"{item['path']} differs from its recorded digest")
    # Units: re-read the run directories and re-evaluate validity from scratch.
    units = latest_units(entries)
    for (step_id, trial_id), recorded_unit in units.items():
        step = runbook.step(step_id)
        plan_path = resolve(repo, step["plan"])
        plan = read_json_file(plan_path)
        trial = next((t for t in plan["trials"] if t["id"] == trial_id), None)
        if trial is None:
            out.append(f"{step_id}/{trial_id}: not a trial of the plan")
            continue
        fresh = evaluate_unit(repo, runbook, step, plan, sha256_file(plan_path), trial)
        for key in ("receipt_sha256", "artifacts", "valid", "unit_statement", "receipt_status"):
            if fresh.get(key) != recorded_unit.get(key):
                out.append(f"{step_id}/{trial_id}: {key} recorded as {recorded_unit.get(key)!r}, "
                           f"now {fresh.get(key)!r}")
        if fresh.get("run_dir"):
            unit_root = resolve(repo, fresh["run_dir"])
            if path in unit_root.parents:
                out += local_unit_findings(repo, unit_root, recorded_unit, recorded)
        if rerun_checks and fresh["valid"]:
            out += rerun_check(repo, runbook, step, trial, resolve(repo, fresh["run_dir"]))
    # Coverage: every trial of every executed trials step has exactly its unit.
    for step in runbook.doc["steps"]:
        if step["kind"] != "trials":
            continue
        ran = any(e["type"] == "step_finished" and e["step_id"] == step["id"] for e in entries)
        if not ran:
            continue
        expected = {t["id"] for t in plan_trials(runbook, step["id"])}
        have = {trial for (sid, trial) in units if sid == step["id"]}
        if expected != have:
            out.append(f"{step['id']}: units {sorted(have)} do not cover the plan's trials {sorted(expected)}")
    # Nothing in the session directory that the journal does not account for.
    for file in sorted(path.rglob("*")):
        if file.is_file() and rel(repo, file) not in recorded and \
                rel(repo, file) != f"{rel(repo, path)}/journal.jsonl":
            out.append(f"{rel(repo, file)} is in the session directory but not in the journal")
    if finished:
        fresh_summary = build_summary(runbook, entries[:finished[-1]["seq"]])
        if canonical(fresh_summary) != canonical(finished[-1].get("summary")):
            out.append("the recorded summary does not match a recomputation from the journal and outputs")
    return out


def local_unit_findings(repo: Path, unit_root: Path, unit: dict[str, Any], recorded: set[str]) -> list[str]:
    """A local unit's receipt binds every file its run produced; nothing may
    be added to or changed in the directory afterwards."""
    receipt = unit_root / "local-receipt.json"
    expected = unit.get("unreceipted_files") or {}
    if receipt.is_file():
        try:
            expected = read_json_file(receipt).get("files_sha256") or {}
        except (OSError, ValueError):
            expected = {}
        recorded.add(rel(repo, receipt))
    out = []
    for file in sorted(unit_root.rglob("*")):
        if not file.is_file() or file == receipt:
            continue
        name = file.relative_to(unit_root).as_posix()
        if name not in expected:
            out.append(f"{rel(repo, file)} was added to the unit after its receipt")
        elif sha256_file(file) != expected[name]:
            out.append(f"{rel(repo, file)} changed after its receipt")
        recorded.add(rel(repo, file))
    for name in expected:
        if not (unit_root / name).is_file():
            out.append(f"{rel(repo, unit_root)}/{name} is in the receipt but missing")
    return out


def rerun_check(repo: Path, runbook: Runbook, step: dict[str, Any], trial: dict[str, Any],
                directory: Path) -> list[str]:
    run_dir = rel(repo, directory) if step["engine"] == "local" else str(directory)
    argv = [a.replace("{run_dir}", run_dir) for a in trial["check_argv"]]
    done = subprocess.run(argv, cwd=repo, env=_subprocess_env(runbook), capture_output=True,
                          timeout=trial.get("watchdog_seconds") or step["timeout_seconds"], check=False)
    if done.returncode != 0:
        return [f"{step['id']}/{trial['id']}: checker exits {done.returncode} on the recorded output"]
    return []


