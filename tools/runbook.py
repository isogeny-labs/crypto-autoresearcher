def brief(repo: Path, session: str | Path) -> str:
    path, entries, runbook = load_session(repo, session)
    last = entries[-1]
    lines = [f"experiment: {runbook.experiment_id}",
             f"session: {rel(repo.resolve(), path)}",
             f"status: {last.get('status') if last['type'] == 'session_finished' else 'running or interrupted'}",
             f"journal tip: {last['hash']} ({len(entries)} entries)"]
    summary = last.get("summary") if last["type"] == "session_finished" else build_summary(runbook, entries)
    for step_id, status in summary["steps"].items():
        lines.append(f"step {step_id}: {status}")
    lines.append(f"units: {summary['units']['valid']} valid of {summary['units']['total']}"
                 + (f"; invalid {summary['units']['invalid']}" if summary["units"]["invalid"] else ""))
    for name, metric in summary["metrics"].items():
        values = ", ".join(f"{k}={_fmt(v)}" for k, v in metric["values"].items())
        lines.append(f"metric {name} ({metric['label']}, {metric['unit']}, n={metric['n']}): {values}")
    lines.append(f"execution validity: {summary['execution_validity']}; control validity: "
                 f"{summary['control_validity']}; inferential validity: {summary['inferential_validity']}")
    proofs = summary["execution_proofs"]
    lines.append(f"execution proofs: {proofs['verified_units']} verified, {proofs['unavailable_units']} "
                 f"unavailable, {proofs['failed_units']} failed ({proofs['chain']})")
    for item in summary["lean_obligations"]:
        lines.append(f"lean {item['step_id']}: {item['status']}" + (f" ({item['detail']})" if item["detail"] else ""))
    failure = last.get("failure") if last["type"] == "session_finished" else None
    if failure:
        lines.append(f"stopped at {failure['step_id']}: {failure['class']}: {failure['detail']}")
        if failure.get("tell"):
            lines.append(f"runbook says: {failure['tell']}")
    return "\n".join(lines)


def _fmt(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:.6g}"
    return json.dumps(value)


def report(repo: Path, session: str | Path) -> Path:
    """The run report research-visuals requires, generated from the journal.

    Observations only: what ran, what it recorded, what is missing. No verdict.
    """
    repo = repo.resolve()
    path, entries, runbook = load_session(repo, session)
    last = entries[-1]
    if last["type"] != "session_finished":
        raise RunbookError("report a session only after it has finished")
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%MZ")
    target = resolve(repo, f"{runbook.base_dir}/reports/run-{stamp}")
    if target.exists():
        target = resolve(repo, f"{runbook.base_dir}/reports/run-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}")
    target.mkdir(parents=True, exist_ok=False)
    summary = last["summary"]
    units = latest_units(entries)
    graph_metric = (runbook.doc.get("report") or {}).get("graph_metric")
    series: list[tuple[str, float]] = []
    if graph_metric:
        metric = next(m for m in runbook.doc["metrics"] if m["name"] == graph_metric)
        values, _ = metric_values(runbook, metric, units)
        series = [(t, float(v)) for t, v in values if isinstance(v, (int, float)) and not isinstance(v, bool)]
    data = {"generator": "tools/runbook.py report", "tool_sha256": sha256_file(Path(__file__).resolve()),
            "experiment_id": runbook.experiment_id, "session_dir": rel(repo, path),
            "journal_tip": last["hash"], "status": last.get("status"), "failure": last.get("failure"),
            "summary": summary, "graph": {"metric": graph_metric, "points": series},
            "units": [{k: u[k] for k in ("step_id", "trial_id", "run_id", "valid", "receipt_status",
                                          "detail", "control")} for u in units.values()]}
    (target / "data.json").write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
    if len(series) >= 2:
        metric = next(m for m in runbook.doc["metrics"] if m["name"] == graph_metric)
        caption = (f"{graph_metric} per trial ({metric['label']}, {metric['unit']}), n={len(series)}, "
                   f"session {runbook.doc['session_id']}")
        (target / "graph.svg").write_text(strip_plot_svg(series, metric["unit"], caption))
    else:
        (target / "graph.svg").write_text(pipeline_svg(runbook, summary))
    (target / "report.typ").write_text(report_typst(runbook, rel(repo, path), entries, data))
    blocked = render_pdf(target)
    if blocked:
        (target / "RENDER-BLOCKED.txt").write_text(blocked + "\n")
    return target


def strip_plot_svg(series: list[tuple[str, float]], unit: str, caption: str) -> str:
    width, height, left, right, top, bottom = 720, 360, 90, 20, 30, 70
    values = [v for _, v in series]
    lo, hi = min(values), max(values)
    if lo == hi:
        lo, hi = lo - 1, hi + 1
    span = hi - lo
    plot_w, plot_h = width - left - right, height - top - bottom

    def x(i: int) -> float:
        return left + (i + 0.5) * plot_w / len(series)

    def y(v: float) -> float:
        return top + plot_h - (v - lo) / span * plot_h

    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
             f'viewBox="0 0 {width} {height}" font-family="Helvetica, Arial, sans-serif" font-size="11">',
             '<rect width="100%" height="100%" fill="#ffffff"/>',
             f'<line x1="{left}" y1="{top}" x2="{left}" y2="{top + plot_h}" stroke="#333"/>',
             f'<line x1="{left}" y1="{top + plot_h}" x2="{left + plot_w}" y2="{top + plot_h}" stroke="#333"/>']
    for tick in range(5):
        v = lo + span * tick / 4
        parts.append(f'<line x1="{left - 4}" y1="{y(v):.1f}" x2="{left + plot_w}" y2="{y(v):.1f}" stroke="#ddd"/>')
        parts.append(f'<text x="{left - 8}" y="{y(v) + 4:.1f}" text-anchor="end">{_svg(f"{v:.6g}")}</text>')
    mean = sum(values) / len(values)
    parts.append(f'<line x1="{left}" y1="{y(mean):.1f}" x2="{left + plot_w}" y2="{y(mean):.1f}" '
                 f'stroke="#c0392b" stroke-dasharray="5,4"/>')
    parts.append(f'<text x="{left + plot_w}" y="{y(mean) - 4:.1f}" text-anchor="end" fill="#c0392b">'
                 f'mean {_svg(f"{mean:.6g}")}</text>')
    for i, (trial, v) in enumerate(series):
        parts.append(f'<circle cx="{x(i):.1f}" cy="{y(v):.1f}" r="3.5" fill="#1f5fa8"/>')
        if len(series) <= 24:
            parts.append(f'<text x="{x(i):.1f}" y="{top + plot_h + 14}" text-anchor="end" '
                         f'transform="rotate(-45 {x(i):.1f} {top + plot_h + 14})">{_svg(trial)}</text>')
    parts.append(f'<text x="18" y="{top + plot_h / 2:.1f}" transform="rotate(-90 18 {top + plot_h / 2:.1f})" '
                 f'text-anchor="middle">{_svg(unit)}</text>')
    parts.append(f'<text x="{width / 2}" y="{height - 8}" text-anchor="middle">{_svg(caption)}</text>')
    parts.append("</svg>\n")
    return "\n".join(parts)


def pipeline_svg(runbook: Runbook, summary: dict[str, Any]) -> str:
    steps = list(summary["steps"].items())
    width, height = 720, 60 + 44 * len(steps)
    colors = {"passed": "#2e7d32", "unavailable": "#9e9e9e", "failed": "#c62828", "not_run": "#bdbdbd"}
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
             f'font-family="Helvetica, Arial, sans-serif" font-size="12">',
             '<rect width="100%" height="100%" fill="#ffffff"/>',
             f'<text x="20" y="24">{_svg(runbook.experiment_id)}: steps as recorded (fewer than two '
             f'comparable values to plot)</text>']
    for i, (step_id, status) in enumerate(steps):
        top = 40 + 44 * i
        parts.append(f'<rect x="20" y="{top}" width="680" height="34" rx="4" fill="none" '
                     f'stroke="{colors.get(status, "#333")}" stroke-width="2"/>')
        parts.append(f'<text x="32" y="{top + 22}">{_svg(step_id)}: {_svg(status)}</text>')
    parts.append("</svg>\n")
    return "\n".join(parts)


def _svg(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def _t(text: Any) -> str:
    """Text as a Typst string literal, so no character is read as markup."""
    value = str(text).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
    return f'#"{value}"'


def report_typst(runbook: Runbook, session: str, entries: list[dict[str, Any]], data: dict[str, Any]) -> str:
    summary = data["summary"]
    last = entries[-1]
    started = entries[0]
    pre = started.get("preflight") or {}
    lines = [
        '#set page(paper: "a4", margin: 2cm)',
        "#set text(size: 10pt)",
        f"= {_t('Run report: ' + runbook.experiment_id)}",
        "",
        _t("This report records what ran and what it measured. It is generated by tools/runbook.py "
           "from the session journal. It states no verdict, support, weakening or significance; "
           "the evidence review does that."),
        "",
        f"- {_t('Runbook: ' + runbook.path + ' (sha256 ' + runbook.sha256 + ')')}",
        f"- {_t('Session: ' + session)}",
        f"- {_t('Journal tip: ' + last['hash'] + ' (' + str(len(entries)) + ' entries)')}",
        f"- {_t('Commit: ' + str(pre.get('commit')) + '; tracked files dirty: ' + str(pre.get('tracked_dirty')))}",
        f"- {_t('Started ' + started['time'] + ', finished ' + last['time'] + '; status ' + str(last.get('status')))}",
        "",
        f"== {_t('Purpose')}",
        _t(runbook.doc["purpose"]),
        "",
        f"== {_t('Steps')}",
        "#table(columns: 3,",
        f"  [*{_t('step')}*], [*{_t('status')}*], [*{_t('what it does')}*],",
    ]
    for step in runbook.doc["steps"]:
        lines.append(f"  [{_t(step['id'])}], [{_t(summary['steps'].get(step['id'], 'not_run'))}], "
                     f"[{_t(step['explain'])}],")
    lines += [")", "", f"== {_t('Units')}",
              _t(f"{summary['units']['valid']} valid of {summary['units']['total']}; invalid: "
                 f"{summary['units']['invalid'] or 'none'}"),
              "", "#table(columns: 4,",
              f"  [*{_t('trial')}*], [*{_t('run')}*], [*{_t('receipt status')}*], [*{_t('valid')}*],"]
    for unit in data["units"]:
        lines.append(f"  [{_t(unit['trial_id'] + (' (control)' if unit['control'] else ''))}], "
                     f"[{_t(unit['run_id'])}], [{_t(unit['receipt_status'])}], [{_t(unit['valid'])}],")
    lines += [")", "", f"== {_t('Metrics')}",
              _t("Each value is computed by tools/runbook.py from the recorded outputs named in its source. "
                 "Labels say whether a value was measured or derived from measured values."),
              "", "#table(columns: 5,",
              f"  [*{_t('metric')}*], [*{_t('label')}*], [*{_t('unit')}*], [*{_t('n')}*], [*{_t('values')}*],"]
    for name, metric in summary["metrics"].items():
        values = ", ".join(f"{k}={_fmt(v)}" for k, v in metric["values"].items())
        lines.append(f"  [{_t(name)}], [{_t(metric['label'])}], [{_t(metric['unit'])}], [{_t(metric['n'])}], "
                     f"[{_t(values)}],")
    lines += [")", "", "#figure(image(\"graph.svg\", width: 100%), caption: [" +
              _t("Recorded values from this session only; no new computation.") + "])", "",
              f"== {_t('Validity, proofs and formal obligations')}",
              f"- {_t('Execution validity: ' + summary['execution_validity'])}",
              f"- {_t('Control validity: ' + summary['control_validity'])}",
              f"- {_t('Inferential validity: ' + summary['inferential_validity'])}",
              f"- {_t('Execution proofs: ' + json.dumps(summary['execution_proofs']))}"]
    for item in summary["lean_obligations"]:
        lines.append(f"- {_t('Lean ' + item['step_id'] + ': ' + item['status'] + ' ' + item['detail'])}")
    lines.append(f"- {_t('Audit: ' + summary['audit'])}")
    failure = last.get("failure")
    if failure:
        lines += ["", f"== {_t('Where it stopped')}",
                  _t(f"{failure['step_id']}: {failure['class']}: {failure['detail']}"),
                  "", _t("A stop is an operational fact. It is not evidence about the hypothesis.")]
    return "\n".join(lines) + "\n"


# Where research-visuals installs Typst when a container has no renderer.
TYPST_VENV_PYTHON = Path(os.environ.get("RUNBOOK_TYPST_PYTHON", "/tmp/report-venv/bin/python"))
TYPST_INSTALL = "python3 -m venv /tmp/report-venv && /tmp/report-venv/bin/pip install -q typst"


def render_pdf(target: Path) -> str | None:
    """Compile report.typ to report.pdf. None on success, else the blocker."""
    source, output = target / "report.typ", target / "report.pdf"
    try:
        import typst  # type: ignore
        typst.compile(str(source), output=str(output))
        return None
    except ImportError:
        pass
    except Exception as exc:  # the compiler's own error types vary by version
        return f"typst (Python) failed: {exc}"
    if program_path("typst"):
        done = subprocess.run(["typst", "compile", "report.typ", "report.pdf"], cwd=target,
                              capture_output=True, text=True, check=False)
        return None if done.returncode == 0 else f"typst CLI failed: {done.stderr.strip()[:500]}"
    if TYPST_VENV_PYTHON.is_file():
        done = subprocess.run([str(TYPST_VENV_PYTHON), "-c",
                               "import sys, typst; typst.compile(sys.argv[1], output=sys.argv[2])",
                               str(source), str(output)], capture_output=True, text=True, check=False)
        return None if done.returncode == 0 else f"typst ({TYPST_VENV_PYTHON}) failed: {done.stderr.strip()[:500]}"
    return (f"no Typst renderer is installed. Run exactly: {TYPST_INSTALL} ; then run exactly: "
            f"python3 tools/runbook.py render {target.as_posix()}")


def render(repo: Path, report_dir: str | Path) -> str | None:
    """Finish a report whose PDF could not be rendered when it was generated."""
    repo = repo.resolve()
    target = Path(report_dir)
    target = (target if target.is_absolute() else repo / target).resolve()
    if not (target / "report.typ").is_file() or not (target / "data.json").is_file():
        raise RunbookError(f"{report_dir} is not a runbook report directory")
    if (target / "report.pdf").exists():
        raise RunbookError(f"{report_dir} already has report.pdf; reports are write-once")
    blocked = render_pdf(target)
    if blocked is None and (target / "RENDER-BLOCKED.txt").exists():
        (target / "RENDER-BLOCKED.txt").unlink()
    return blocked


def publish_paths(repo: Path, session: str | Path) -> dict[str, Any]:
    repo = repo.resolve()
    path, entries, runbook = load_session(repo, session)
    paths = [rel(repo, path)]
    for unit in latest_units(entries).values():
        if unit.get("run_dir") and path not in resolve(repo, unit["run_dir"]).parents:
            paths.append(unit["run_dir"])
    reports = resolve(repo, f"{runbook.base_dir}/reports")
    tip = entries[-1]["hash"]
    if reports.is_dir():
        for data in sorted(reports.glob("run-*/data.json")):
            try:
                if read_json_file(data).get("journal_tip") == tip:
                    paths.append(rel(repo, data.parent))
            except (OSError, ValueError):
                continue
    status = entries[-1].get("status", "unfinished")
    message = f"run({runbook.experiment_id}): runbook session {runbook.doc['session_id']} {status}"
    return {"paths": paths, "commit_message": message,
            "commands": [" ".join(["git", "add", "--", *paths]), f'git commit -m "{message}"',
                         "git push -u origin HEAD"]}


