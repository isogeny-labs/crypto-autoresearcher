def entry_hash(entry: dict[str, Any]) -> str:
    body = {k: v for k, v in entry.items() if k != "hash"}
    return sha256_bytes(DOMAIN_JOURNAL + canonical(body))


class Journal:
    """Append-only, hash-chained JSON lines. Only this class writes it."""

    def __init__(self, path: Path):
        self.path = path
        self.entries: list[dict[str, Any]] = []
        if path.exists():
            self.entries = read_journal(path)

    @property
    def tip(self) -> str:
        return self.entries[-1]["hash"] if self.entries else GENESIS

    def append(self, entry_type: str, **fields: Any) -> dict[str, Any]:
        entry = {"seq": len(self.entries), "type": entry_type, "time": utcnow(), **fields,
                 "prev": self.tip}
        entry["hash"] = entry_hash(entry)
        line = json.dumps(entry, sort_keys=True, ensure_ascii=False, allow_nan=False) + "\n"
        with self.path.open("a", encoding="utf-8") as handle:
            handle.write(line)
            handle.flush()
            os.fsync(handle.fileno())
        self.entries.append(entry)
        return entry


def read_journal(path: Path) -> list[dict[str, Any]]:
    entries = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            raise RunbookError(f"{path}: blank line {number}")
        entries.append(json.loads(line))
    return entries


def chain_findings(entries: list[dict[str, Any]]) -> list[str]:
    out = []
    previous = GENESIS
    for index, entry in enumerate(entries):
        if entry.get("seq") != index:
            out.append(f"journal entry {index}: seq is {entry.get('seq')} (entries removed, inserted or reordered)")
        if entry.get("prev") != previous:
            out.append(f"journal entry {index}: prev does not match entry {index - 1}'s hash")
        if entry.get("hash") != entry_hash(entry):
            out.append(f"journal entry {index}: content does not match its hash (edited after writing)")
        previous = entry.get("hash")
    return out


