def metric_values(runbook: Runbook, metric: dict[str, Any], units: dict[tuple[str, str], dict[str, Any]]
                  ) -> tuple[list[tuple[str, Any]], list[str]]:
    step = runbook.step(metric["step"])
    selected = metric.get("trials", "all")
    values, excluded = [], []
    for trial in plan_trials(runbook, metric["step"]):
        if selected == "all" and trial["id"] in (step.get("controls") or []):
            continue
        if selected != "all" and trial["id"] not in selected:
            continue
        unit = units.get((metric["step"], trial["id"]))
        if not unit or not unit["valid"] or not unit.get("run_dir"):
            excluded.append(trial["id"])
            continue
        path = resolve(runbook.repo, unit["run_dir"]) / metric["file"]
        try:
            found, value = pointer_get(read_json_file(path), metric["pointer"])
        except (OSError, ValueError):
            found, value = False, None
        if found:
            values.append((trial["id"], value))
        else:
            excluded.append(trial["id"])
    return values, excluded


def aggregate(name: str, values: list[Any]) -> Any:
    if name == "count":
        return len(values)
    if name == "fraction_true":
        flags = [v for v in values if isinstance(v, bool)]
        return (sum(flags) / len(flags)) if flags and len(flags) == len(values) else None
    numbers = [v for v in values if isinstance(v, (int, float)) and not isinstance(v, bool)]
    if not numbers or len(numbers) != len(values):
        return None
    if name == "sum":
        return sum(numbers)
    if name == "mean":
        return sum(numbers) / len(numbers)
    if name == "min":
        return min(numbers)
    if name == "max":
        return max(numbers)
    return statistics.median(numbers)


def build_summary(runbook: Runbook, entries: list[dict[str, Any]]) -> dict[str, Any]:
    units = latest_units(entries)
    steps = {}
    for step in runbook.doc["steps"]:
        finished = [e for e in entries if e["type"] == "step_finished" and e["step_id"] == step["id"]]
        steps[step["id"]] = finished[-1]["status"] if finished else "not_run"
    metrics = {}
    for metric in runbook.doc.get("metrics") or []:
        values, excluded = metric_values(runbook, metric, units)
        raw = [v for _, v in values]
        metrics[metric["name"]] = {
            "unit": metric["unit"], "label": metric["label"], "n": len(raw),
            "excluded_trials": excluded,
            "values": {agg: aggregate(agg, raw) for agg in metric["aggregate"]},
            "source": f"{metric['step']}:{metric['file']}{metric['pointer']}"}
    unit_list = list(units.values())
    controls = [u for u in unit_list if u.get("control")]
    latest: dict[str, dict[str, Any]] = {}
    for entry in entries:
        if entry["type"] == "step_finished":
            latest[entry["step_id"]] = entry
    proof_units = [u for sid, e in latest.items() if runbook.step(sid)["kind"] == "execution_proof"
                   for u in (e.get("data") or {}).get("units", [])]
    lean = [{"step_id": sid, "status": e["status"], "detail": e.get("detail", "")}
            for sid, e in latest.items() if runbook.step(sid)["kind"] == "lean"]
    all_done = all(status in ("passed", "unavailable") for status in steps.values())
    return {
        "steps": steps,
        "units": {"total": len(unit_list), "valid": sum(1 for u in unit_list if u["valid"]),
                  "invalid": sorted(u["trial_id"] for u in unit_list if not u["valid"])},
        "metrics": metrics,
        # Three independent facts (docs/execution-proof-chain.md). The third is
        # never this tool's to assess.
        "execution_validity": "complete" if all_done and all(u["valid"] for u in unit_list)
        else "incomplete",
        "control_validity": ("not_applicable" if not controls else
                             "passed" if all(u["valid"] for u in controls) else "failed"),
        "inferential_validity": "not_assessed: review-evidence and the Coordinator decide",
        "lean_obligations": lean,
        "execution_proofs": {
            "verified_units": sum(1 for u in proof_units if u.get("status") == "verified"),
            "unavailable_units": sum(1 for u in proof_units if u.get("status") == "unavailable"),
            "failed_units": sum(1 for u in proof_units if u.get("status") == "failed"),
            "chain": "incomplete: docs/execution-proof-chain.md milestones are open",
        },
        "audit": "not audited: tools/runbook.py audit (audit-runs skill)",
    }


