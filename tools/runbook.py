    def run_lean(self, journal: Journal, step: dict[str, Any], attempt: int, out_dir: Path) -> StepResult:
        task_file = step["task_file"]
        task = yaml.safe_load(resolve(self.repo, task_file).read_text(encoding="utf-8"))
        data: dict[str, Any] = {"task_file": task_file, "theorem_name": task.get("theorem_name")}
        if program_path("lake") is None:
            detail = "lake is not on PATH: install Lean with formal/setup.sh on this host"
            if step["required"]:
                return StepResult("failed", "infrastructure_error", detail, data=data)
            return StepResult("unavailable", detail=detail, data=data)
        receipt = out_dir / "lean-receipt.json"
        stdout, stderr = self._logs(step["id"], attempt)
        argv = ["python3", "-m", "orchestration.formal.cli", "--repo-root", str(self.repo), "verify",
                "--task-file", task_file, "--artifact-out", rel(self.repo, receipt),
                "--build-timeout", str(step["timeout_seconds"])]
        data["argv"] = argv
        code, timed_out = run_process(argv, cwd=self.repo, env=_subprocess_env(self.runbook),
                                      timeout=step["timeout_seconds"] + 120, stdout=stdout, stderr=stderr)
        if timed_out:
            return StepResult("failed", "resource_exhaustion", "Lean verification timed out", None, True, data=data)
        if code == 3:
            return StepResult("failed", "infrastructure_error", "Lean infrastructure failure (exit 3)", code, data=data)
        checks = lean_receipt_checks(self.repo, step, receipt)
        data["validity"] = checks
        failed = [c for c in checks if not c["passed"]]
        if code != 0 or failed:
            detail = "; ".join(f for c in failed for f in c["failures"]) or f"exit {code}"
            result = StepResult("failed", "implementation_error",
                                f"Lean obligation not machine-verified: {detail}"[:2000], code,
                                validity_failed=bool(failed), data=data)
            if not step["required"]:
                result.status, result.detail = "unavailable", f"optional obligation not verified: {detail}"[:2000]
                result.failure_class = None
            return result
        return StepResult("passed", exit_code=code, data=data)

