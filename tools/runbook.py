#!/usr/bin/env python3
"""Frozen runbooks: experiments a judgment-free executor runs and an auditor
checks without trusting the executor.

`docs/runbook-execution.md` is the design. In short, an experiment's design
session (`design-experiment`, Coordinator authority) writes
`experiments/<EXP>/runbook.yaml` beside its specification and trial plan. The
runbook names every step, every command, every file whose bytes matter, the
validity post-conditions of every output, what each failure means and what
happens next. Nothing is left to the operator, so the operator can be the
mechanical tier (`executor-mechanical`, Haiku): it runs a fixed sequence of
commands from this tool and relays the tool's output verbatim.

The operator never writes a number. This tool writes every record:

  * a hash-chained journal (`journal.jsonl`) of every step, attempt, unit and
    output digest, so a later edit, deletion, reorder or insertion is visible;
  * the session summary (metrics, coverage, validity facts), computed here from
    the declared outputs, never typed by a model;
  * the run report directory (`report`), generated from the journal.

Scientific trials run only through `tools/experiment_execution.py` (the
`supervisor` engine), with its own admission, claim, resource and receipt
checks; this tool wraps it and never replaces it. The `local` engine exists for
`EXAMPLE-*` runbooks and conformance tests, which have no queue or claim.

The audit (`audit`) is the independent half: it re-verifies the chain and
every digest, re-runs the declared checkers, recomputes the summary, and
re-executes a sample of trials chosen from a nonce the auditor picks after the
session is published, so the executor cannot know in advance which units will
be replayed. None of this is an execution proof: `execution_proof` steps verify
real zkVM receipts when a pinned verifier exists, and record `unavailable`
otherwise (`docs/execution-proof-chain.md`).

    python3 tools/runbook.py lint   <runbook.yaml>
    python3 tools/runbook.py plan   <runbook.yaml>
    python3 tools/runbook.py run    <runbook.yaml> [--as ADDR]
    python3 tools/runbook.py status <session_dir> [--brief]
    python3 tools/runbook.py verify <session_dir> [--rerun-checks]
    python3 tools/runbook.py report <session_dir>
    python3 tools/runbook.py render <report_dir>
    python3 tools/runbook.py publish-paths <session_dir>
    python3 tools/runbook.py audit  <session_dir> [--samples K] [--nonce HEX]
                                    [--float-tolerance rel_tol=R,abs_tol=A]
    python3 tools/runbook.py pending-audits [--json]

Exit status: 0 ok; 1 a lint, verify or audit finding; 2 an impediment (the run
refused to start); 3 the session stopped on a recorded failure.
"""
