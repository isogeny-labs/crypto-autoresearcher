def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo", type=Path, default=REPO, help="repository root (default: this checkout)")
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("lint", "plan"):
        p = sub.add_parser(name)
        p.add_argument("runbook")
    p = sub.add_parser("run", help="execute a runbook, or resume its session")
    p.add_argument("runbook")
    p.add_argument("--as", dest="owner", help="lowercase bus address for the claim (default: generated)")
    p = sub.add_parser("render", help="render report.pdf for a report generated without a renderer")
    p.add_argument("report_dir")
    for name in ("status", "verify", "report", "publish-paths"):
        p = sub.add_parser(name)
        p.add_argument("session")
        if name == "status":
            p.add_argument("--brief", action="store_true")
        if name == "verify":
            p.add_argument("--rerun-checks", action="store_true")
    p = sub.add_parser("audit", help="independent integrity and replay audit of a finished session")
    p.add_argument("session")
    p.add_argument("--samples", type=int, help="units to replay per trials step (default: the runbook's)")
    p.add_argument("--nonce", help="auditor-chosen hex; default: fresh randomness")
    p.add_argument("--out", help="audit directory (default: <experiment>/audits/AUD-...)")
    p.add_argument("--auditor", default="unspecified", help="who ran this audit (role and model)")
    p.add_argument("--float-tolerance", metavar="rel_tol=R,abs_tol=A",
                   help="compare float leaves of fields pointers the runbook gives no tolerance under "
                        "math.isclose with these bounds; recorded in audit.json (default: exact)")
    p = sub.add_parser("pending-audits")
    p.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    repo = args.repo.resolve()
    try:
        if args.command in ("lint", "plan"):
            runbook = load_runbook(repo, args.runbook)
            findings = lint(runbook)
            if args.command == "lint":
                for finding in findings:
                    print(f"LINT: {finding}")
                print(f"LINT OK {runbook.path} sha256 {runbook.sha256}" if not findings
                      else f"LINT FAILED: {len(findings)} finding(s)")
                return 1 if findings else 0
            print(json.dumps({"runbook": runbook.path, "sha256": runbook.sha256, "lint": findings,
                              "session_dir": runbook.session_dir,
                              "steps": [{"id": s.get("id"), "kind": s.get("kind"), "title": s.get("title"),
                                         "argv": s.get("argv"),
                                         "trials": [t.get("id") for t in plan_trials(runbook, s.get("id"))]}
                                        for s in runbook.doc.get("steps") or []]}, indent=2))
            return 1 if findings else 0
        if args.command == "run":
            result = Runner(load_runbook(repo, args.runbook), owner=args.owner).run()
            print(json.dumps(result, sort_keys=True))
            return 0 if result["status"] == "completed" else 3
        if args.command == "status":
            if args.brief:
                print(brief(repo, args.session))
            else:
                _, entries, _ = load_session(repo, args.session)
                print(json.dumps(entries[-1], indent=2, sort_keys=True))
            return 0
        if args.command == "verify":
            findings = verify(repo, args.session, rerun_checks=args.rerun_checks)
            for finding in findings:
                print(f"VERIFY: {finding}")
            print("VERIFY OK" if not findings else f"VERIFY FAILED: {len(findings)} finding(s)")
            return 1 if findings else 0
        if args.command == "report":
            target = report(repo, args.session)
            print(rel(repo, target))
            blocked = target / "RENDER-BLOCKED.txt"
            if blocked.exists():
                print(f"PDF NOT RENDERED: {blocked.read_text().strip()}")
            return 0
        if args.command == "render":
            blocked = render(repo, args.report_dir)
            print(f"PDF NOT RENDERED: {blocked}" if blocked else f"RENDERED {args.report_dir}/report.pdf")
            return 1 if blocked else 0
        if args.command == "publish-paths":
            result = publish_paths(repo, args.session)
            print("\n".join(result["commands"]))
            return 0
        if args.command == "audit":
            result, target = audit(repo, args.session, samples=args.samples, nonce=args.nonce,
                                   out_dir=args.out, auditor=args.auditor,
                                   float_tolerance=args.float_tolerance)
            print(json.dumps({"verdict": result["verdict"], "audit_dir": rel(repo, target),
                              "findings": result["findings"], "replayed_units": len(result["replays"]),
                              "replay_results": result["replay_results"],
                              "environment_drift": result["environment_drift"],
                              "not_covered": result["not_covered"]}, indent=2))
            return 0 if result["verdict"] == "clean" else 1
        rows = pending_audits(repo)
        if args.json:
            print(json.dumps(rows, indent=2))
        else:
            for row in rows:
                print(f"{row['session_dir']}  {row['status']}  finished {row['finished_at']}")
            print(f"{len(rows)} session(s) awaiting audit")
        return 0
    except (RunbookError, OSError, ValueError, KeyError) as exc:
        print(f"IMPEDIMENT: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
