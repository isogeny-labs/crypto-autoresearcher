def _text_findings(where: str, text: Any, *, operator_facing: bool) -> list[str]:
    if not isinstance(text, str) or not text.strip():
        return [f"{where}: must be non-empty text"]
    pattern = VAGUE if operator_facing else PLACEHOLDER_TEXT
    hits = sorted({m.group(0) for m in pattern.finditer(text)})
    if hits:
        what = "leaves a choice to the operator" if operator_facing else "is unfinished"
        return [f"{where}: {what} ({', '.join(repr(h) for h in hits)}); state exactly what happens"]
    return []


def _assertion_findings(where: str, assertions: Any, *, unit_context: bool,
                        artifacts: Iterable[str] = ()) -> list[str]:
    out: list[str] = []
    if not isinstance(assertions, list) or not assertions:
        return [f"{where}: assertions must be a non-empty list"]
    for index, item in enumerate(assertions):
        at = f"{where}[{index}]"
        if not isinstance(item, dict) or not isinstance(item.get("pointer"), str):
            out.append(f"{at}: each assertion needs a JSON pointer")
            continue
        if item["pointer"] and not item["pointer"].startswith("/"):
            out.append(f"{at}: pointer must start with '/'")
        ops = [key for key in item if key != "pointer"]
        if len(ops) != 1 or ops[0] not in ASSERTION_OPS:
            out.append(f"{at}: exactly one operator from {', '.join(ASSERTION_OPS)}")
            continue
        op, value = ops[0], item[ops[0]]
        if op == "type" and value not in JSON_TYPES:
            out.append(f"{at}: type must be one of {', '.join(JSON_TYPES)}")
        if op in ("min", "max") and (isinstance(value, bool) or not isinstance(value, (int, float))):
            out.append(f"{at}: {op} needs a number")
        if op in ("length", "min_length") and (isinstance(value, bool) or not isinstance(value, int) or value < 0):
            out.append(f"{at}: {op} needs a non-negative integer")
        if op == "in" and not isinstance(value, list):
            out.append(f"{at}: in needs a list")
        if op == "exists" and not isinstance(value, bool):
            out.append(f"{at}: exists needs true or false")
        if op == "matches":
            try:
                re.compile(value)
            except (re.error, TypeError):
                out.append(f"{at}: matches needs a valid regular expression")
        if op == "equals_artifact_sha256":
            if not unit_context:
                out.append(f"{at}: equals_artifact_sha256 is only meaningful for a trial unit")
            elif value not in set(artifacts):
                out.append(f"{at}: {value!r} is not a declared artifact of the unit")
        for template in PLACEHOLDER.findall(json.dumps(value)):
            if not unit_context or template not in ("trial_id", "run_id"):
                out.append(f"{at}: unknown placeholder {{{template}}}")
    return out


def _on_failure_findings(where: str, rules: Any) -> list[str]:
    if rules is None:
        return []
    if not isinstance(rules, list):
        return [f"{where}: on_failure must be a list"]
    out = []
    for index, rule in enumerate(rules):
        at = f"{where}[{index}]"
        if not isinstance(rule, dict) or set(rule) - {"when", "class", "action", "max_attempts"}:
            out.append(f"{at}: keys are when, class, action, max_attempts")
            continue
        when = rule.get("when")
        if not isinstance(when, dict) or len(when) != 1 or not (
                ("exit_code" in when and isinstance(when["exit_code"], int) and not isinstance(when["exit_code"], bool))
                or when.get("timed_out") is True or when.get("validity") is False):
            out.append(f"{at}: when is exactly one of {{exit_code: N}}, {{timed_out: true}}, {{validity: false}}")
        if rule.get("class") not in FAILURE_CLASSES:
            out.append(f"{at}: class must be one of {', '.join(FAILURE_CLASSES)}")
        action = rule.get("action")
        if action not in ("stop", "retry"):
            out.append(f"{at}: action is stop or retry")
        if action == "retry":
            if rule.get("class") not in RETRYABLE:
                out.append(f"{at}: only {', '.join(RETRYABLE)} may retry; "
                           "anything else is a result or a defect, never noise")
            attempts = rule.get("max_attempts")
            if not isinstance(attempts, int) or isinstance(attempts, bool) or not 2 <= attempts <= MAX_ATTEMPTS:
                out.append(f"{at}: retry needs max_attempts between 2 and {MAX_ATTEMPTS}")
        elif "max_attempts" in rule:
            out.append(f"{at}: max_attempts applies only to retry")
    return out


def lint(runbook: Runbook) -> list[str]:
    """Every finding that keeps this runbook from being executable as written."""
    repo, doc = runbook.repo, runbook.doc
    out: list[str] = []
    unknown = set(doc) - TOP_KEYS
    missing = TOP_REQUIRED - set(doc)
    if unknown:
        out.append(f"unknown top-level keys: {sorted(unknown)}")
    if missing:
        out.append(f"missing top-level keys: {sorted(missing)}")
        return out
    if doc["schema"] != SCHEMA:
        out.append(f"schema must be {SCHEMA}")
    exp = doc["experiment_id"]
    if not isinstance(exp, str) or not EXPERIMENT_ID.match(exp):
        out.append("experiment_id must be EXP-... or EXAMPLE-...")
        return out
    if not isinstance(doc["session_id"], str) or not SESSION_ID.match(doc["session_id"]):
        out.append("session_id must be RBS-<AREA>-<6 hex>, allocated when the runbook is frozen")
    out += _text_findings("title", doc["title"], operator_facing=True)
    out += _text_findings("purpose", doc["purpose"], operator_facing=False)
    if doc["executor_tier"] not in ("mechanical", "implementation"):
        out.append("executor_tier must be mechanical or implementation")
    approval = doc["approval"]
    mode = approval.get("mode") if isinstance(approval, dict) else None
    if not isinstance(approval, dict) or set(approval) != {"mode"} or mode not in ("decision_record", "example"):
        out.append("approval must be {mode: decision_record} (EXP-*) or {mode: example} (EXAMPLE-*)")
    elif (mode == "example") != runbook.is_example:
        out.append("approval mode example is only for EXAMPLE-* runbooks, and every EXP-* runbook "
                   "needs a committed decision record naming its sha256")

    bound: dict[str, str] = {}
    if not isinstance(doc["binds"], list) or not doc["binds"]:
        out.append("binds must list every file whose bytes this run depends on")
    else:
        for index, item in enumerate(doc["binds"]):
            at = f"binds[{index}]"
            if not isinstance(item, dict) or set(item) != {"path", "sha256"}:
                out.append(f"{at}: each bind is {{path, sha256}}")
                continue
            try:
                relative = safe_relative(item["path"])
                path = resolve(repo, relative)
            except RunbookError as exc:
                out.append(f"{at}: {exc}")
                continue
            if relative in bound:
                out.append(f"{at}: {relative} is bound twice")
            if relative == runbook.path:
                out.append(f"{at}: a runbook cannot bind itself (hash cycle)")
            if not isinstance(item["sha256"], str) or not SHA256.match(item["sha256"]):
                out.append(f"{at}: sha256 must be 64 lowercase hex")
            elif not path.is_file():
                out.append(f"{at}: {relative} does not exist")
            elif sha256_file(path) != item["sha256"]:
                out.append(f"{at}: {relative} has changed since the runbook was frozen")
            bound[relative] = item["sha256"]

    for index, item in enumerate(doc.get("spec_bindings") or []):
        at = f"spec_bindings[{index}]"
        if not isinstance(item, dict) or set(item) != {"file", "pointer", "equals"}:
            out.append(f"{at}: each spec binding is {{file, pointer, equals}}")
            continue
        if item["file"] not in bound:
            out.append(f"{at}: {item['file']} must be in binds")
            continue
        try:
            path = resolve(repo, item["file"])
            data = (read_json_file(path) if path.suffix == ".json"
                    else yaml.safe_load(path.read_text(encoding="utf-8")))
        except (OSError, ValueError, yaml.YAMLError, RunbookError) as exc:
            out.append(f"{at}: cannot read {item['file']}: {exc}")
            continue
        found, value = pointer_get(data, item["pointer"])
        if not found:
            out.append(f"{at}: {item['pointer']} does not exist in {item['file']}")
        elif value != item["equals"]:
            out.append(f"{at}: {item['file']}{item['pointer']} is {value!r}, the runbook says {item['equals']!r}")

    env = doc.get("environment") or {}
    programs: set[str] = set()
    if not isinstance(env, dict) or set(env) - {"python", "programs", "env"}:
        out.append("environment keys are python, programs, env")
    else:
        if "python" in env and not (isinstance(env["python"], str) and re.fullmatch(r"3\.\d{1,2}", env["python"])):
            out.append("environment.python is a major.minor string such as '3.11'")
        programs = set(env.get("programs") or [])
        if not all(isinstance(p, str) and p for p in programs):
            out.append("environment.programs lists program names")
        overlay = env.get("env") or {}
        if not isinstance(overlay, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in overlay.items()):
            out.append("environment.env maps names to string values")
        else:
            for key in overlay:
                if DENIED_ENV.match(key):
                    out.append(f"environment.env: {key} may not be set by a runbook")

    steps = doc["steps"]
    if not isinstance(steps, list) or not steps:
        out.append("steps must be a non-empty list")
        return out
    seen: dict[str, dict[str, Any]] = {}
    last_number = 0
    for index, step in enumerate(steps):
        at = f"steps[{index}]"
        if not isinstance(step, dict):
            out.append(f"{at}: a step is a mapping")
            continue
        step_id = step.get("id")
        match = STEP_ID.match(step_id) if isinstance(step_id, str) else None
        if not match:
            out.append(f"{at}: id must look like S01-short-name")
        else:
            at = step_id
            number = int(match.group(1))
            if number <= last_number:
                out.append(f"{at}: step numbers must increase")
            last_number = number
            if step_id in seen:
                out.append(f"{at}: duplicate step id")
            seen[step_id] = step
        kind = step.get("kind")
        if kind not in STEP_KINDS:
            out.append(f"{at}: kind must be one of {', '.join(STEP_KINDS)}")
            continue
        extra = set(step) - STEP_KEYS[kind]
        if extra:
            out.append(f"{at}: unknown keys for a {kind} step: {sorted(extra)}")
        out += _text_findings(f"{at}.title", step.get("title"), operator_facing=True)
        out += _text_findings(f"{at}.explain", step.get("explain"), operator_facing=True)
        if "tell_on_failure" in step:
            out += _text_findings(f"{at}.tell_on_failure", step["tell_on_failure"], operator_facing=True)
        timeout = step.get("timeout_seconds")
        if not isinstance(timeout, int) or isinstance(timeout, bool) or not 1 <= timeout <= 7 * 86400:
            out.append(f"{at}: timeout_seconds must be an integer from 1 to 604800")
        out += _on_failure_findings(f"{at}.on_failure", step.get("on_failure"))
        if kind == "command":
            out += _lint_command(runbook, at, step, programs, bound)
        elif kind == "trials":
            out += _lint_trials(runbook, at, step, bound)
        elif kind == "lean":
            out += _lint_lean(runbook, at, step, bound)
        else:
            out += _lint_proof(runbook, at, step, seen)

    trial_steps = {sid for sid, s in seen.items() if s.get("kind") == "trials"}
    names = set()
    for index, metric in enumerate(doc.get("metrics") or []):
        at = f"metrics[{index}]"
        if not isinstance(metric, dict) or set(metric) - {"name", "unit", "label", "step", "file", "pointer", "aggregate", "trials"}:
            out.append(f"{at}: keys are name, unit, label, step, file, pointer, aggregate, trials")
            continue
        name = metric.get("name")
        if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", name) or name in names:
            out.append(f"{at}: name must be a unique snake_case identifier")
        names.add(name)
        if not isinstance(metric.get("unit"), str) or not metric["unit"]:
            out.append(f"{at}: unit is required (a number without a unit is incomplete)")
        if metric.get("label") not in ("measured", "derived"):
            out.append(f"{at}: label is measured or derived")
        if metric.get("step") not in trial_steps:
            out.append(f"{at}: step must name a trials step")
            continue
        trials = plan_trials(runbook, metric["step"])
        selected = metric.get("trials", "all")
        ids = {t.get("id") for t in trials}
        if selected != "all" and (not isinstance(selected, list) or not set(selected) <= ids):
            out.append(f"{at}: trials is 'all' or a list of trial ids in the plan")
            selected_trials = []
        else:
            selected_trials = trials if selected == "all" else [t for t in trials if t.get("id") in selected]
        for trial in selected_trials:
            if metric.get("file") not in trial.get("artifacts", []):
                out.append(f"{at}: {metric.get('file')!r} is not an artifact of trial {trial.get('id')}")
                break
        if not isinstance(metric.get("pointer"), str) or not metric["pointer"].startswith("/"):
            out.append(f"{at}: pointer must start with '/'")
        aggregate = metric.get("aggregate")
        if not isinstance(aggregate, list) or not aggregate or not set(aggregate) <= set(AGGREGATES):
            out.append(f"{at}: aggregate is a list from {', '.join(AGGREGATES)}")
    report = doc.get("report")
    if report is not None:
        if not isinstance(report, dict) or set(report) - {"graph_metric"}:
            out.append("report keys are graph_metric")
        elif report.get("graph_metric") not in names:
            out.append("report.graph_metric must name a declared metric")
    return out


def _lint_command(runbook: Runbook, at: str, step: dict[str, Any], programs: set[str],
                  bound: dict[str, str]) -> list[str]:
    out = []
    if step.get("purpose") not in COMMAND_PURPOSES:
        out.append(f"{at}: purpose must be one of {', '.join(COMMAND_PURPOSES)}; "
                   "scientific trials run only in a trials step")
    argv = step.get("argv")
    if not isinstance(argv, list) or not argv or not all(isinstance(a, str) and a for a in argv):
        return out + [f"{at}: argv is a non-empty list of strings (never a shell string)"]
    if argv[0] not in programs:
        out.append(f"{at}: {argv[0]!r} must be listed in environment.programs")
    for token in argv:
        if token in SHELL_TOKENS or token.startswith("$("):
            out.append(f"{at}: {token!r} is shell syntax; argv runs without a shell")
        for name in PLACEHOLDER.findall(token):
            if name not in ("out", "session_dir"):
                out.append(f"{at}: unknown placeholder {{{name}}} (allowed: {{out}}, {{session_dir}})")
        out += _bound_token(runbook, at, token, bound)
    validity = step.get("validity")
    if not isinstance(validity, dict) or set(validity) - {"exit_code", "outputs", "stdout_matches"}:
        return out + [f"{at}: validity is {{exit_code, outputs, stdout_matches}}"]
    if not isinstance(validity.get("exit_code"), int) or isinstance(validity.get("exit_code"), bool):
        out.append(f"{at}: validity.exit_code is required")
    if "stdout_matches" in validity:
        try:
            re.compile(validity["stdout_matches"])
        except (re.error, TypeError):
            out.append(f"{at}: validity.stdout_matches needs a valid regular expression")
    for index, output in enumerate(validity.get("outputs") or []):
        where = f"{at}.validity.outputs[{index}]"
        if not isinstance(output, dict) or set(output) - {"path", "json", "assertions"}:
            out.append(f"{where}: keys are path, json, assertions")
            continue
        path = output.get("path")
        if not isinstance(path, str) or not path.startswith("{out}/"):
            out.append(f"{where}: an output path starts with {{out}}/ (the step's own attempt directory)")
        if "assertions" in output:
            if output.get("json") is not True:
                out.append(f"{where}: assertions need json: true")
            out += _assertion_findings(f"{where}.assertions", output["assertions"], unit_context=False)
    return out


def _bound_token(runbook: Runbook, at: str, token: str, bound: dict[str, str]) -> list[str]:
    """Every repository file an argv names must be bound by digest."""
    if PLACEHOLDER.search(token) or token.startswith("-"):
        return []
    try:
        relative = safe_relative(token)
        path = resolve(runbook.repo, relative)
    except RunbookError:
        return []
    if path.is_file() and relative not in bound:
        return [f"{at}: argv names {relative}, which is not in binds"]
    return []


def _lint_trials(runbook: Runbook, at: str, step: dict[str, Any], bound: dict[str, str]) -> list[str]:
    out = []
    plan_path = step.get("plan")
    if not isinstance(plan_path, str) or plan_path not in bound:
        return [f"{at}: plan must be a trial-plan.json listed in binds"]
    plan = runbook.plans.get(step["id"])
    if not isinstance(plan, dict):
        return [f"{at}: {plan_path} is not readable JSON"]
    if plan.get("schema") != PLAN_SCHEMA or plan.get("frozen") is not True:
        out.append(f"{at}: {plan_path} must be a frozen {PLAN_SCHEMA}")
    if plan.get("experiment_id") != runbook.experiment_id:
        out.append(f"{at}: the plan is for {plan.get('experiment_id')}, the runbook for {runbook.experiment_id}")
    engine = step.get("engine")
    if engine not in ENGINES:
        out.append(f"{at}: engine is supervisor or local")
    elif engine == "local" and not runbook.is_example:
        out.append(f"{at}: the local engine is for EXAMPLE-* runbooks; scientific trials run "
                   "through tools/experiment_execution.py (engine: supervisor)")
    elif engine == "supervisor":
        if runbook.is_example:
            out.append(f"{at}: an EXAMPLE-* runbook has no queue or claim; use engine: local")
        else:
            out += _lint_supervisor_queue(runbook, at, plan)
        claim = step.get("claim")
        ttl = claim.get("ttl_minutes") if isinstance(claim, dict) else None
        if not isinstance(claim, dict) or set(claim) != {"ttl_minutes"} or not isinstance(ttl, int) \
                or isinstance(ttl, bool) or ttl < 1:
            out.append(f"{at}: claim is {{ttl_minutes: N}}, sized to cover the step's timeout")
        elif isinstance(step.get("timeout_seconds"), int) and ttl * 60 < step["timeout_seconds"]:
            out.append(f"{at}: claim.ttl_minutes must cover timeout_seconds, or the claim expires mid-run")
    elif "claim" in step:
        out.append(f"{at}: claim applies only to the supervisor engine")
    trials = plan.get("trials")
    if not isinstance(trials, list) or not trials:
        return out + [f"{at}: the plan has no trials"]
    ids = [t.get("id") for t in trials if isinstance(t, dict)]
    artifacts = {t.get("id"): list(t.get("artifacts") or []) for t in trials if isinstance(t, dict)}
    for trial in trials:
        if not isinstance(trial, dict) or not all(isinstance(trial.get(k), list) for k in ("argv", "check_argv", "artifacts")) \
                or not isinstance(trial.get("run_id"), str):
            out.append(f"{at}: every plan trial needs id, run_id, argv, check_argv, artifacts")
    if engine == "local":
        for source, digest in (plan.get("source_sha256") or {}).items():
            try:
                if sha256_file(resolve(runbook.repo, source)) != digest:
                    out.append(f"{at}: plan source {source} has changed since the plan was frozen")
            except (OSError, RunbookError):
                out.append(f"{at}: plan source {source} is missing")
        if not plan.get("source_sha256"):
            out.append(f"{at}: the plan must hash-bind its sources (source_sha256)")
    validity = step.get("validity")
    if not isinstance(validity, dict) or set(validity) != {"files"} or not isinstance(validity["files"], list) \
            or not validity["files"]:
        out.append(f"{at}: validity is {{files: [...]}} with at least one file assertion block")
        validity = {"files": []}
    blocks = [("validity", None, validity["files"])]
    by_trial = step.get("by_trial") or {}
    if not isinstance(by_trial, dict):
        out.append(f"{at}: by_trial maps trial ids to {{files: [...]}}")
        by_trial = {}
    for trial_id, block in by_trial.items():
        if trial_id not in ids:
            out.append(f"{at}: by_trial names {trial_id}, which is not in the plan")
            continue
        if not isinstance(block, dict) or set(block) != {"files"} or not isinstance(block["files"], list):
            out.append(f"{at}.by_trial.{trial_id}: is {{files: [...]}}")
            continue
        blocks.append((f"by_trial.{trial_id}", trial_id, block["files"]))
    for label, trial_id, files in blocks:
        targets = [trial_id] if trial_id else ids
        for index, item in enumerate(files):
            where = f"{at}.{label}.files[{index}]"
            if not isinstance(item, dict) or set(item) - {"path", "json", "assertions"} or "path" not in item:
                out.append(f"{where}: keys are path, json, assertions")
                continue
            for target in targets:
                if item["path"] not in artifacts.get(target, []):
                    out.append(f"{where}: {item['path']!r} is not a declared artifact of trial {target}")
                    break
            if "assertions" in item:
                if item.get("json") is not True:
                    out.append(f"{where}: assertions need json: true")
                common = set.intersection(*(set(artifacts.get(t, [])) for t in targets)) if targets else set()
                out += _assertion_findings(f"{where}.assertions", item["assertions"],
                                           unit_context=True, artifacts=common)
    if runbook.doc.get("executor_tier") == "mechanical":
        # "With the right parameters": every unit's output must be tied to the
        # unit that produced it, by a per-trial block or a {trial_id}/{run_id}
        # template, or an output from one unit can stand in for another's.
        templated = "{trial_id}" in json.dumps(validity["files"]) or "{run_id}" in json.dumps(validity["files"])
        if not templated:
            unbound = [t for t in ids if t not in by_trial]
            if unbound:
                out.append(f"{at}: mechanical tier: trials {unbound} have no assertion tying their output to "
                           "their prescribed parameters (add by_trial blocks or a {trial_id} assertion)")
    controls = step.get("controls") or []
    if not isinstance(controls, list) or not set(controls) <= set(ids):
        out.append(f"{at}: controls lists trial ids from the plan")
    replay = step.get("replay")
    if not isinstance(replay, dict) or replay.get("mode") not in REPLAY_MODES:
        out.append(f"{at}: replay.mode is fields, bytes or exempt (the audit replays a sample of units)")
    else:
        mode = replay["mode"]
        allowed = {"mode", "sample"} | ({"exempt_reason"} if mode == "exempt" else {"compare"})
        if set(replay) - allowed:
            out.append(f"{at}: replay keys for mode {mode}: {sorted(allowed)}")
        if mode == "exempt":
            out += _text_findings(f"{at}.replay.exempt_reason", replay.get("exempt_reason"), operator_facing=False)
        else:
            compare = replay.get("compare")
            if not isinstance(compare, list) or not compare:
                out.append(f"{at}: replay.compare lists what a replay must reproduce")
            else:
                for index, item in enumerate(compare):
                    where = f"{at}.replay.compare[{index}]"
                    keys = {"file", "pointers"} if mode == "fields" else {"file"}
                    optional = {"tolerance"} if mode == "fields" else set()
                    if not isinstance(item, dict) or not keys <= set(item) <= keys | optional:
                        out.append(f"{where}: keys are {sorted(keys)}"
                                   + (f", optionally {sorted(optional)}" if optional else ""))
                        continue
                    if "tolerance" in item:
                        try:
                            parse_tolerance(item["tolerance"])
                        except RunbookError as exc:
                            out.append(f"{where}.tolerance: {exc}")
                    if any(item["file"] not in artifacts.get(t, []) for t in ids):
                        out.append(f"{where}: {item['file']!r} is not an artifact of every trial")
                    if mode == "fields" and (not isinstance(item["pointers"], list) or not item["pointers"]
                                             or not all(isinstance(p, str) and p.startswith("/") for p in item["pointers"])):
                        out.append(f"{where}: pointers is a non-empty list of JSON pointers")
            sample = replay.get("sample", 1)
            if not isinstance(sample, int) or isinstance(sample, bool) or sample < 1:
                out.append(f"{at}: replay.sample is a positive integer")
    if step.get("on_invalid", "stop") not in ("stop", "continue"):
        out.append(f"{at}: on_invalid is stop or continue")
    return out


def _lint_supervisor_queue(runbook: Runbook, at: str, plan: dict[str, Any]) -> list[str]:
    """The supervisor refuses a trial whose run files the task does not
    declare. Find that at design time, not after a claim is published."""
    queue_path, task_id = plan.get("queue"), plan.get("task_id")
    try:
        queue = read_json_file(resolve(runbook.repo, queue_path))
    except (OSError, ValueError, RunbookError):
        return [f"{at}: the plan's queue {queue_path!r} is not readable"]
    task = next((t for t in queue.get("tasks") or [] if t.get("id") == task_id), None)
    if task is None:
        return [f"{at}: the plan's task {task_id} is not in {queue_path}"]
    out = []
    if task.get("role") != "executor":
        out.append(f"{at}: {task_id} is a {task.get('role')!r} task; the supervisor runs executor tasks")
    declared = set(task.get("artifact_paths") or [])
    parent = PurePosixPath(str(plan.get("specification"))).parent
    missing = [f"{parent}/runs/{t.get('run_id')}/{name}" for t in plan.get("trials") or [] if isinstance(t, dict)
               for name in (*SUPERVISOR_GENERATED, *(t.get("artifacts") or []))
               if f"{parent}/runs/{t.get('run_id')}/{name}" not in declared]
    if missing:
        out.append(f"{at}: the supervisor will refuse this plan: {len(missing)} run file(s) are not in "
                   f"{task_id}'s artifact_paths (first: {missing[0]})")
    session = runbook.session_dir
    if not any(session == s or session.startswith(str(s).rstrip("/") + "/") for s in task.get("write_scope") or []):
        out.append(f"{at}: {task_id}'s write_scope does not include {session}")
    return out


def _lint_lean(runbook: Runbook, at: str, step: dict[str, Any], bound: dict[str, str]) -> list[str]:
    out = []
    task_file = step.get("task_file")
    if not isinstance(task_file, str) or task_file not in bound:
        return [f"{at}: task_file must be a formal target listed in binds"]
    if not isinstance(step.get("required"), bool):
        out.append(f"{at}: required is true or false")
    try:
        task = yaml.safe_load(resolve(runbook.repo, task_file).read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError, RunbookError) as exc:
        return out + [f"{at}: cannot read {task_file}: {exc}"]
    if not isinstance(task, dict) or task.get("schema") != FORMAL_TASK_SCHEMA:
        return out + [f"{at}: {task_file} is not a {FORMAL_TASK_SCHEMA}"]
    theorem = f"{task.get('workspace', 'formal')}/{task.get('theorem_file')}"
    if theorem not in bound:
        out.append(f"{at}: the theorem file {theorem} must be in binds, or a weakened "
                   "statement could verify in its place")
    return out


def _lint_proof(runbook: Runbook, at: str, step: dict[str, Any],
                seen: dict[str, dict[str, Any]]) -> list[str]:
    out = []
    source = seen.get(step.get("of_step"))
    if not source or source.get("kind") != "trials":
        return [f"{at}: of_step must name an earlier trials step"]
    trials = plan_trials(runbook, step["of_step"])
    ids = [t.get("id") for t in trials]
    selected = step.get("trials", "all")
    if selected != "all" and (not isinstance(selected, list) or not set(selected) <= set(ids)):
        out.append(f"{at}: trials is 'all' or a list of plan trial ids")
        selected = []
    chosen = trials if selected == "all" else [t for t in trials if t.get("id") in selected]
    receipt = step.get("receipt_file")
    if not isinstance(receipt, str) or any(receipt not in t.get("artifacts", []) for t in chosen):
        out.append(f"{at}: receipt_file must be a declared artifact of every proved trial")
    if step.get("backend") not in PROOF_BACKENDS:
        out.append(f"{at}: backend is one of {', '.join(PROOF_BACKENDS)}")
    if not isinstance(step.get("image_id"), str) or not HEX.match(step["image_id"]):
        out.append(f"{at}: image_id is the pinned guest image id (lowercase hex)")
    verifier = step.get("verifier")
    if not isinstance(verifier, dict) or set(verifier) != {"program", "sha256"} \
            or not isinstance(verifier.get("program"), str) or not SHA256.match(str(verifier.get("sha256"))):
        out.append(f"{at}: verifier is {{program, sha256}}: the verifier binary is pinned by digest")
    args = step.get("verifier_args")
    if not isinstance(args, list) or not all(isinstance(a, str) for a in args) \
            or "{receipt}" not in args or "{out}" not in args:
        out.append(f"{at}: verifier_args must pass {{receipt}} and {{out}}")
    else:
        for token in args:
            for name in PLACEHOLDER.findall(token):
                if name not in ("receipt", "out", "image_id"):
                    out.append(f"{at}: unknown placeholder {{{name}}} in verifier_args")
    if not isinstance(step.get("required"), bool):
        out.append(f"{at}: required is true or false")
    journal = step.get("journal")
    if journal is not None:
        common = set.intersection(*(set(t.get("artifacts", [])) for t in chosen)) if chosen else set()
        out += _assertion_findings(f"{at}.journal", journal, unit_context=True, artifacts=common)
    return out


