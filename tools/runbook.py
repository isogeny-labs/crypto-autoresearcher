@dataclass
class StepResult:
    status: str                      # passed | failed | unavailable
    failure_class: str | None = None
    detail: str = ""
    exit_code: int | None = None
    timed_out: bool = False
    validity_failed: bool = False
    data: dict[str, Any] = field(default_factory=dict)


def _subprocess_env(runbook: Runbook) -> dict[str, str]:
    env = dict(os.environ)
    env.update((runbook.doc.get("environment") or {}).get("env") or {})
    return env


def run_process(argv: list[str], *, cwd: Path, env: dict[str, str], timeout: int,
                stdout: Path, stderr: Path, memory_mb: int | None = None) -> tuple[int | None, bool]:
    """Run argv without a shell, in its own process group. (exit code, timed out)."""
    def limits() -> None:
        if memory_mb and sys.platform.startswith("linux"):
            import resource
            size = memory_mb * 1024 * 1024
            resource.setrlimit(resource.RLIMIT_AS, (size, size))
    stdout.parent.mkdir(parents=True, exist_ok=True)
    with stdout.open("xb") as out, stderr.open("xb") as err:
        try:
            process = subprocess.Popen(argv, cwd=cwd, env=env, stdout=out, stderr=err,
                                       stdin=subprocess.DEVNULL, start_new_session=True,
                                       preexec_fn=limits if memory_mb else None)
        except OSError as exc:
            err.write(f"cannot start {argv[0]}: {exc}\n".encode())
            return None, False
        try:
            return process.wait(timeout=timeout), False
        except subprocess.TimeoutExpired:
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            process.wait()
            return None, True


def _classify(step: dict[str, Any], result: StepResult, default: str) -> tuple[str, dict[str, Any] | None]:
    for rule in step.get("on_failure") or []:
        when = rule["when"]
        if ("exit_code" in when and result.exit_code == when["exit_code"]) \
                or (when.get("timed_out") and result.timed_out) \
                or (when.get("validity") is False and result.validity_failed):
            return rule["class"], rule
    return default, None


class Runner:
    def __init__(self, runbook: Runbook, owner: str | None = None):
        self.runbook = runbook
        self.repo = runbook.repo
        self.session = resolve(self.repo, runbook.session_dir)
        self.owner = owner

    # -- preflight ---------------------------------------------------------

    def preflight(self) -> dict[str, Any]:
        """Everything that must hold before step one. Any failure is an
        impediment: nothing is written and the session does not start."""
        runbook = self.runbook
        findings = lint(runbook)
        if findings:
            raise RunbookError("the runbook does not lint clean:\n  " + "\n  ".join(findings))
        facts: dict[str, Any] = {}
        if not runbook.is_example:
            for relative in [runbook.path, *(b["path"] for b in runbook.doc["binds"])]:
                if not committed_bytes_match(self.repo, relative):
                    raise RunbookError(f"{relative} is not committed as-is at HEAD; a runbook runs "
                                       "only from committed, approved bytes")
            facts["approval_record"] = find_approval(self.repo, runbook.experiment_id, runbook.sha256)
            if facts["approval_record"] is None:
                raise RunbookError(
                    f"no committed ledger/decisions record approves {runbook.experiment_id} with "
                    f"runbook_sha256 {runbook.sha256}")
        env = runbook.doc.get("environment") or {}
        missing = [p for p in env.get("programs") or [] if program_path(p) is None]
        if missing:
            raise RunbookError(f"required programs are not on PATH: {missing}")
        if "python" in env:
            have = f"{sys.version_info.major}.{sys.version_info.minor}"
            probe = subprocess.run(["python3", "-c", "import sys;print(f'{sys.version_info[0]}.{sys.version_info[1]}')"],
                                   capture_output=True, text=True, check=False)
            have = probe.stdout.strip() or have
            if have != env["python"]:
                raise RunbookError(f"python3 is {have}; the runbook requires {env['python']}")
            facts["python"] = have
        code, head = git(self.repo, "rev-parse", "HEAD")
        facts["commit"] = head.decode().strip() if code == 0 else None
        code, dirty = git(self.repo, "status", "--porcelain", "--untracked-files=no")
        facts["tracked_dirty"] = bool(dirty.strip()) if code == 0 else None
        facts["tool_sha256"] = sha256_file(Path(__file__).resolve())
        facts["platform"] = sys.platform
        return facts

    # -- the session -------------------------------------------------------

    def run(self) -> dict[str, Any]:
        runbook = self.runbook
        journal_path = self.session / "journal.jsonl"
        # Before anything is written: a session id belongs to one execution
        # (RBS-ICPERF-b7e41c had two). Read-only git; never fetches.
        collisions = session_id_collisions(self.repo, rel(self.repo, journal_path),
                                           journal_path.read_bytes() if journal_path.exists() else None)
        if collisions:
            raise RunbookError("refusing to write this session:\n  " + "\n  ".join(collisions))
        if journal_path.exists():
            journal = Journal(journal_path)
            problems = chain_findings(journal.entries)
            if problems:
                raise RunbookError("the existing journal does not verify; it is preserved as is:\n  "
                                   + "\n  ".join(problems))
            start = journal.entries[0]
            if start.get("runbook_sha256") != runbook.sha256:
                raise RunbookError("this session was started from different runbook bytes")
            self.owner = start.get("owner")
            finished = [e for e in journal.entries if e["type"] == "session_finished"]
            reopened = [e for e in journal.entries if e["type"] == "session_reopened"]
            if len(finished) > len(reopened):
                last = finished[-1]
                failure = last.get("failure") or {}
                if last.get("status") == "completed":
                    return self.final(journal, last)
                if failure.get("class") not in REOPENABLE:
                    return self.final(journal, last)
                facts = self.preflight()
                journal.append("session_reopened", reason=f"previous stop was {failure.get('class')}",
                               preflight=facts)
            else:
                facts = self.preflight()
                journal.append("session_resumed", preflight=facts)
        else:
            facts = self.preflight()
            self.owner = self.owner or f"runbook-{secrets.token_hex(3)}"
            if not OWNER.match(self.owner):
                raise RunbookError(f"--as {self.owner!r} is not a lowercase bus address")
            self.session.mkdir(parents=True, exist_ok=False)
            (self.session / "steps").mkdir()
            (self.session / "outputs").mkdir()
            journal = Journal(journal_path)
            journal.append("session_started", schema=SCHEMA, experiment_id=runbook.experiment_id,
                           session_id=runbook.doc["session_id"], runbook=runbook.path,
                           runbook_sha256=runbook.sha256, binds=runbook.doc["binds"],
                           environment_overlay=(runbook.doc.get("environment") or {}).get("env") or {},
                           owner=self.owner, preflight=facts)
        return self.execute(journal)

    def execute(self, journal: Journal) -> dict[str, Any]:
        failure = None
        for step in self.runbook.doc["steps"]:
            state = step_state(journal.entries, step["id"])
            if state["done"]:
                continue
            attempt = state["attempts"] + 1
            if state["open_attempt"] is not None:
                # Whatever the interrupted attempt left is preserved and bound,
                # so it is neither lost nor mistaken for a later attempt's.
                outputs, logs = self.attempt_files(step["id"], state["open_attempt"])
                journal.append("step_interrupted", step_id=step["id"], attempt=state["open_attempt"],
                               outputs=outputs, logs=logs)
            if attempt > MAX_INTERRUPTED_ATTEMPTS:
                failure = {"step_id": step["id"], "class": "infrastructure_error",
                           "detail": f"{attempt - 1} attempts started without finishing"}
                break
            while True:
                print(f"[{step['id']}] attempt {attempt}: {step['title']}", flush=True)
                result = self.attempt(journal, step, attempt)
                print(f"[{step['id']}] {result.status}"
                      + (f" ({result.failure_class}): {result.detail}" if result.status == "failed" else ""),
                      flush=True)
                if result.status != "failed":
                    break
                rule = result.data.get("rule")
                if rule and rule["action"] == "retry" and attempt < rule["max_attempts"]:
                    attempt += 1
                    continue
                failure = {"step_id": step["id"], "class": result.failure_class, "detail": result.detail,
                           "tell": step.get("tell_on_failure")}
                break
            if failure:
                break
        summary = build_summary(self.runbook, journal.entries)
        last = journal.append("session_finished", status="stopped" if failure else "completed",
                              failure=failure, summary=summary)
        return self.final(journal, last)

    def final(self, journal: Journal, last: dict[str, Any]) -> dict[str, Any]:
        session = rel(self.repo, self.session)
        return {"status": last.get("status"), "session_dir": session,
                "experiment_id": self.runbook.experiment_id, "journal_tip": journal.tip,
                "failure": last.get("failure"),
                "next_command": f"python3 tools/runbook.py verify {session}"}

    def attempt(self, journal: Journal, step: dict[str, Any], attempt: int) -> StepResult:
        out_dir = self.session / "outputs" / step["id"] / f"attempt-{attempt}"
        # Journal first: a crash after this line leaves an open attempt that a
        # resume closes as interrupted and never reuses.
        journal.append("step_started", step_id=step["id"], attempt=attempt, kind=step["kind"],
                       out=rel(self.repo, out_dir))
        out_dir.mkdir(parents=True, exist_ok=False)
        handler = {"command": self.run_command, "trials": self.run_trials,
                   "lean": self.run_lean, "execution_proof": self.run_proof}[step["kind"]]
        try:
            result = handler(journal, step, attempt, out_dir)
        except Exception as exc:  # recorded, never swallowed: the step failed
            result = StepResult("failed", "infrastructure_error", f"{type(exc).__name__}: {exc}")
        if result.status == "failed":
            default = result.failure_class or "implementation_error"
            result.failure_class, rule = _classify(step, result, default)
            if rule:
                result.data["rule"] = rule
        outputs, logs = self.attempt_files(step["id"], attempt)
        data = {k: v for k, v in result.data.items() if k != "rule"}
        journal.append("step_finished", step_id=step["id"], attempt=attempt, status=result.status,
                       failure_class=result.failure_class if result.status == "failed" else None,
                       detail=result.detail[:2000], exit_code=result.exit_code, timed_out=result.timed_out,
                       outputs=outputs, logs=logs, data=data)
        return result

    def attempt_files(self, step_id: str, attempt: int) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
        out_dir = self.session / "outputs" / step_id / f"attempt-{attempt}"
        outputs = [{"path": rel(self.repo, p), "sha256": sha256_file(p), "bytes": p.stat().st_size}
                   for p in sorted(out_dir.rglob("*")) if p.is_file()] if out_dir.is_dir() else []
        logs = [{"path": rel(self.repo, p), "sha256": sha256_file(p)}
                for p in sorted((self.session / "steps").glob(f"{step_id}.attempt-{attempt}.*"))]
        return outputs, logs

    def _logs(self, step_id: str, attempt: int, name: str = "") -> tuple[Path, Path]:
        stem = self.session / "steps" / f"{step_id}.attempt-{attempt}{name}"
        return Path(f"{stem}.stdout"), Path(f"{stem}.stderr")

    # -- command -----------------------------------------------------------

    def run_command(self, journal: Journal, step: dict[str, Any], attempt: int, out_dir: Path) -> StepResult:
        out_rel = rel(self.repo, out_dir)
        argv = [token.replace("{out}", out_rel).replace("{session_dir}", rel(self.repo, self.session))
                for token in step["argv"]]
        stdout, stderr = self._logs(step["id"], attempt)
        code, timed_out = run_process(argv, cwd=self.repo, env=_subprocess_env(self.runbook),
                                      timeout=step["timeout_seconds"], stdout=stdout, stderr=stderr)
        validity = step["validity"]
        data: dict[str, Any] = {"argv": argv}
        if timed_out:
            return StepResult("failed", "resource_exhaustion", "timed out", None, True, data=data)
        if code is None:
            return StepResult("failed", "infrastructure_error", f"{argv[0]} did not start", data=data)
        if code != validity["exit_code"]:
            return StepResult("failed", "implementation_error",
                              f"exit code {code}, expected {validity['exit_code']}", code, data=data)
        failures = []
        if "stdout_matches" in validity:
            text = stdout.read_text(encoding="utf-8", errors="replace")[:1 << 20]
            if not re.search(validity["stdout_matches"], text):
                failures.append(f"stdout does not match {validity['stdout_matches']!r}")
        outputs = [dict(o, path=o["path"].replace("{out}/", "", 1)) for o in validity.get("outputs") or []]
        checks = evaluate_file_block(out_dir, outputs)
        failures += [f for c in checks for f in c["failures"]]
        data["validity"] = checks
        if failures:
            return StepResult("failed", "invalid_measurement", "; ".join(failures)[:2000], code,
                              validity_failed=True, data=data)
        return StepResult("passed", exit_code=code, data=data)

    # -- trials ------------------------------------------------------------

    def run_trials(self, journal: Journal, step: dict[str, Any], attempt: int, out_dir: Path) -> StepResult:
        plan_rel = step["plan"]
        plan_path = resolve(self.repo, plan_rel)
        plan = read_json_file(plan_path)
        plan_sha = sha256_file(plan_path)
        if step["engine"] == "supervisor":
            result = self._supervise(journal, step, attempt, plan_rel)
        else:
            result = self._local(step, attempt, plan, plan_sha)
        units = []
        for trial in plan["trials"]:
            unit = self.record_unit(journal, step, plan, plan_sha, trial)
            units.append(unit)
        invalid = [u for u in units if not u["valid"]]
        result.data["units"] = {"total": len(units), "valid": len(units) - len(invalid),
                                "invalid": [u["trial_id"] for u in invalid]}
        if result.status == "failed":
            return result
        if invalid and step.get("on_invalid", "stop") == "stop":
            classes = sorted({u["failure_class"] for u in invalid})
            return StepResult("failed", classes[0] if len(classes) == 1 else "invalid_measurement",
                              f"{len(invalid)} of {len(units)} units invalid: "
                              + "; ".join(f"{u['trial_id']}: {u['detail']}" for u in invalid[:5]),
                              result.exit_code, validity_failed=True, data=result.data)
        return result

    def _supervise(self, journal: Journal, step: dict[str, Any], attempt: int, plan_rel: str) -> StepResult:
        plan = read_json_file(resolve(self.repo, plan_rel))
        queue, task = plan["queue"], plan["task_id"]
        env = _subprocess_env(self.runbook)
        data: dict[str, Any] = {"queue": queue, "task_id": task, "owner": self.owner}
        epoch = self._live_claim_epoch(queue, task)
        if epoch is None:
            stdout, stderr = self._logs(step["id"], attempt, ".claim")
            argv = ["python3", "tools/goal_lanes.py", "claim", queue, task, "--as", self.owner,
                    "--ttl-minutes", str(step["claim"]["ttl_minutes"]), "--publish"]
            code, timed_out = run_process(argv, cwd=self.repo, env=env, timeout=600,
                                          stdout=stdout, stderr=stderr)
            data["claim_argv"] = argv
            if code != 0:
                return StepResult("failed", "infrastructure_error",
                                  f"claim failed (exit {code}); see {rel(self.repo, stderr)}", code, timed_out, data=data)
            epoch = self._live_claim_epoch(queue, task)
            if epoch is None:
                return StepResult("failed", "infrastructure_error", "claim reported success but is not live", data=data)
        data["epoch"] = epoch
        proof = self._sync_claim(step, attempt, queue, task, epoch, env, data)
        if proof is not None:
            # Only release an identity checked against its committed native
            # record. A malformed/foreign claim is never ours to clean up.
            if data.get("claim_identity_verified"):
                self._release_claim(step, attempt, queue, task, epoch, "failed", env, data)
            return proof
        stdout, stderr = self._logs(step["id"], attempt, ".supervisor")
        argv = ["python3", "tools/experiment_execution.py", "run", "--plan", plan_rel,
                "--owner", self.owner, "--epoch", str(epoch)]
        data["supervisor_argv"] = argv
        code, timed_out = run_process(argv, cwd=self.repo, env=env, timeout=step["timeout_seconds"],
                                      stdout=stdout, stderr=stderr)
        outcome = "completed" if code == 0 else "failed"
        release_code, stderr_r = self._release_claim(step, attempt, queue, task, epoch, outcome, env, data)
        if timed_out:
            return StepResult("failed", "resource_exhaustion", "supervisor timed out", None, True, data=data)
        if code != 0:
            meaning = {2: "impediment: the supervisor refused to launch",
                       3: "trials remain or need reconciliation",
                       130: "the supervisor was interrupted"}.get(code, "unexpected exit")
            return StepResult("failed", "infrastructure_error" if code in (2, 130) else "implementation_error",
                              f"supervisor exit {code} ({meaning}); see {rel(self.repo, stderr)}", code, data=data)
        if release_code != 0:
            return StepResult("failed", "infrastructure_error",
                              f"trials completed but the claim release failed (exit {release_code}); "
                              f"see {rel(self.repo, stderr_r)}", code, data=data)
        return StepResult("passed", exit_code=code, data=data)

    def _release_claim(self, step: dict[str, Any], attempt: int, queue: str, task: str,
                       epoch: int, outcome: str, env: dict[str, str], data: dict[str, Any]) -> tuple[int | None, Path]:
        stdout, stderr = self._logs(step["id"], attempt, ".release")
        argv = ["python3", "tools/goal_lanes.py", "release", queue, task, "--as", self.owner,
                "--expected-epoch", str(epoch),
                "--outcome", outcome, "--note", f"runbook session {self.runbook.doc['session_id']}",
                "--publish"]
        code, timed_out = run_process(argv, cwd=self.repo, env=env, timeout=600,
                                      stdout=stdout, stderr=stderr)
        data.update(release_argv=argv, release_expected_epoch=epoch, release_exit_code=code,
                    release_timed_out=timed_out, release_stdout=rel(self.repo, stdout),
                    release_stderr=rel(self.repo, stderr))
        return code, stderr

    def _sync_claim(self, step: dict[str, Any], attempt: int, queue: str, task: str, epoch: int,
                    env: dict[str, str], data: dict[str, Any]) -> StepResult | None:
        """Fetch remote proof for the exact committed native claim, never HEAD.

        Every Git command has exclusive per-attempt logs and a journal-bound
        status. The supervisor's own authorize() remains the final authority.
        """
        commands = data.setdefault("claim_proof", [])

        def command(name: str, *args: str) -> tuple[int | None, bool, bytes]:
            stdout, stderr = self._logs(step["id"], attempt, f".claim-{name}")
            argv = ["git", *args]
            code, timed_out = run_process(argv, cwd=self.repo, env=env, timeout=600,
                                          stdout=stdout, stderr=stderr)
            commands.append({"argv": argv, "exit_code": code, "timed_out": timed_out,
                             "stdout": rel(self.repo, stdout), "stderr": rel(self.repo, stderr)})
            return code, timed_out, stdout.read_bytes()

        def refused(detail: str) -> StepResult:
            return StepResult("failed", "infrastructure_error", detail, data=data)

        code, _, output = command("branch", "symbolic-ref", "--quiet", "--short", "HEAD")
        branch = output.decode("utf-8", errors="replace").strip()
        if code != 0 or not branch or branch == "HEAD":
            return refused("claim proof requires a known current branch; detached HEAD cannot launch")
        code, _, _ = command("branch-format", "check-ref-format", f"refs/heads/{branch}")
        if code != 0:
            return refused("claim proof requires a valid current branch")
        claim_relative = (PurePosixPath(queue).parent / "claims" / f"{task}.{epoch}.claim.json").as_posix()
        try:
            claim_path = resolve(self.repo, claim_relative)
            claim = read_json_file(claim_path)
        except (OSError, ValueError, RunbookError) as exc:
            return refused(f"cannot read exact live claim: {exc}")
        if not isinstance(claim, dict) or any(claim.get(key) != value for key, value in {
                "schema": "crypto.autoresearch.task_claim.v1", "task_id": task, "epoch": epoch,
                "owner": self.owner, "branch": branch}.items()) or type(claim.get("epoch")) is not int:
            return refused("exact live claim identity does not match task/owner/epoch/current branch")
        code, _, output = command("committed", "show", f"HEAD:{claim_relative}")
        if code != 0 or output != claim_path.read_bytes():
            return refused("exact live claim is not committed as-is")
        code, _, output = command("commit", "log", "-1", "--format=%H", "--", claim_relative)
        commit = output.decode("ascii", errors="replace").strip()
        if code != 0 or not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", commit):
            return refused("exact live claim has no native commit")
        data.update(claim_path=claim_relative, claim_commit=commit, claim_branch=branch,
                    claim_identity_verified=True)
        tracking = f"refs/remotes/origin/{branch}"
        code, timed_out, _ = command("fetch", "fetch", "--no-tags", "origin",
                                     f"refs/heads/{branch}:{tracking}")
        if code != 0:
            return refused(f"own-branch claim fetch failed (exit {code}, timed_out={timed_out}); "
                           f"see {commands[-1]['stderr']}")
        code, _, _ = command("contains", "merge-base", "--is-ancestor", commit, tracking)
        if code != 0:
            return refused(f"exact claim commit is not contained in fetched own branch; "
                           f"see {commands[-1]['stderr']}")
        return None

    def _live_claim_epoch(self, queue: str, task: str) -> int | None:
        done = subprocess.run(["python3", "tools/goal_lanes.py", "claims", queue, "--json"],
                              cwd=self.repo, capture_output=True, text=True, timeout=600, check=False)
        if done.returncode != 0:
            return None
        try:
            item = json.loads(done.stdout).get(task) or {}
        except ValueError:
            return None
        if item.get("status") == "live" and item.get("owner") == self.owner:
            epoch = item.get("epoch")
            if type(epoch) is not int or epoch <= 0:
                raise RunbookError("live claim has an invalid epoch")
            return epoch
        return None

    def _local(self, step: dict[str, Any], attempt: int, plan: dict[str, Any], plan_sha: str) -> StepResult:
        """Execute an EXAMPLE plan in the session directory, supervisor-style:
        exclusive run directories, no reuse, a receipt per trial."""
        env = _subprocess_env(self.runbook)
        states: dict[str, str] = {}
        for trial in plan["trials"]:
            directory = self.unit_dir(step, plan, trial)
            receipt = directory / "local-receipt.json"
            if receipt.is_file():
                states[trial["id"]] = read_json_file(receipt).get("status", "needs_reconciliation")
                continue
            if directory.exists():
                states[trial["id"]] = "needs_reconciliation"
                continue
            if any(states.get(dep) != "output_validated" for dep in trial.get("depends_on", [])):
                states[trial["id"]] = "waiting_on_dependencies"
                continue
            directory.mkdir(parents=True)
            run_dir = rel(self.repo, directory)
            argv = [a.replace("{run_dir}", run_dir) for a in trial["argv"]]
            check = [a.replace("{run_dir}", run_dir) for a in trial["check_argv"]]
            timeout = trial.get("watchdog_seconds") or step["timeout_seconds"]
            started = utcnow()
            code, timed_out = run_process(argv, cwd=self.repo, env=env, timeout=timeout,
                                          stdout=directory / "stdout.log", stderr=directory / "stderr.log",
                                          memory_mb=trial.get("memory_mb"))
            check_code = None
            if timed_out:
                status = "watchdog_expired"
            elif code != 0:
                status = "infrastructure_error"
            else:
                check_code, check_timeout = run_process(
                    check, cwd=self.repo, env=env, timeout=timeout,
                    stdout=directory / "check.stdout.log", stderr=directory / "check.stderr.log")
                status = ("watchdog_expired" if check_timeout else
                          "output_validated" if check_code == 0 else "invalid_output")
            if status == "output_validated" and any(
                    not (directory / name).is_file() for name in trial["artifacts"]):
                status = "invalid_output"
            artifacts = {name: sha256_file(directory / name) for name in trial["artifacts"]
                         if (directory / name).is_file()}
            files = {p.relative_to(directory).as_posix(): sha256_file(p)
                     for p in sorted(directory.rglob("*")) if p.is_file()}
            with receipt.open("x", encoding="utf-8") as handle:
                handle.write(json.dumps({
                    "schema": LOCAL_RECEIPT_SCHEMA, "plan_sha256": plan_sha, "trial_id": trial["id"],
                    "run_id": trial["run_id"], "status": status, "returncode": code,
                    "check_returncode": check_code, "started_at": started, "finished_at": utcnow(),
                    "argv": argv, "check_argv": check, "artifact_sha256": artifacts,
                    "files_sha256": files}, indent=2) + "\n")
            states[trial["id"]] = status
        return StepResult("passed", exit_code=0, data={"engine": "local", "states": states})

