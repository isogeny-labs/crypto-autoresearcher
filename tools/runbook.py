@dataclass
class Runbook:
    repo: Path
    path: str                     # repository-relative
    sha256: str
    doc: dict[str, Any]
    plans: dict[str, dict[str, Any]] = field(default_factory=dict)  # step id -> plan

    @property
    def experiment_id(self) -> str:
        return self.doc["experiment_id"]

    @property
    def is_example(self) -> bool:
        return self.experiment_id.startswith("EXAMPLE-")

    @property
    def base_dir(self) -> str:
        return PurePosixPath(self.path).parent.as_posix()

    @property
    def session_dir(self) -> str:
        return f"{self.base_dir}/runbook-sessions/{self.doc['session_id']}"

    def step(self, step_id: str) -> dict[str, Any]:
        for step in self.doc["steps"]:
            if step.get("id") == step_id:
                return step
        raise KeyError(step_id)


def load_runbook(repo: Path, path: str | Path) -> Runbook:
    repo = repo.resolve()
    full = Path(path)
    full = full if full.is_absolute() else (repo / full)
    full = full.resolve()
    relative = rel(repo, full)
    raw = full.read_bytes()
    try:
        doc = yaml.safe_load(raw)
    except yaml.YAMLError as exc:
        raise RunbookError(f"{relative}: YAML does not parse: {exc}") from None
    if not isinstance(doc, dict):
        raise RunbookError(f"{relative}: a runbook is a mapping")
    runbook = Runbook(repo, relative, sha256_bytes(raw), doc)
    for step in doc.get("steps") or []:
        if isinstance(step, dict) and step.get("kind") == "trials" and isinstance(step.get("plan"), str):
            try:
                runbook.plans[step["id"]] = read_json_file(resolve(repo, step["plan"]))
            except (OSError, ValueError, RunbookError):
                pass  # reported by lint
    return runbook


def plan_trials(runbook: Runbook, step_id: str) -> list[dict[str, Any]]:
    return list(runbook.plans.get(step_id, {}).get("trials", []))


def unit_statement(plan_sha: str, trial: dict[str, Any]) -> str:
    """Identity of one prescribed unit of work.

    It covers the frozen plan, the trial and its unexpanded argv, so a result
    or proof recorded for one unit cannot be presented as another's. It does
    not include the runbook digest: the plan is frozen before the runbook, and
    a value derived from the argv cannot appear in that argv (no hash cycles).
    """
    return sha256_bytes(DOMAIN_UNIT + canonical({
        "plan_sha256": plan_sha, "trial_id": trial.get("id"),
        "run_id": trial.get("run_id"), "argv": trial.get("argv"),
        "check_argv": trial.get("check_argv")}))


