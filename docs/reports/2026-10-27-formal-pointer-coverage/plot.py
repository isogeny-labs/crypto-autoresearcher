#!/usr/bin/env python3
"""Render the source-bound pointer coverage counts as an SVG bar figure."""

from html import escape
from pathlib import Path
import json

root = Path(__file__).resolve().parent
d = json.loads((root / 'inventory.json').read_text())
exp_total = d['experiment_directories']
exp_linked = d['experiment_ids_with_exact_formal_pointer']
target_total = d['formal_targets']
target_linked = d['targets_with_exact_experiment_pointer']
commit = escape(d['source_commit'][:12])

x, width = 270, 630
exp_width = width * exp_linked / exp_total
target_width = width * target_linked / target_total

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="470" viewBox="0 0 1000 470">
<rect width="1000" height="470" fill="#ffffff"/>
<text x="50" y="55" font-family="DejaVu Sans, sans-serif" font-size="27" font-weight="bold" fill="#18253b">Formal target pointer inventory</text>
<text x="50" y="83" font-family="DejaVu Sans, sans-serif" font-size="15" fill="#52627a">crypto-autoresearcher main {commit} · 2026-10-27 · syntactic references only</text>
<rect x="50" y="106" width="13" height="13" fill="#245eb4"/>
<text x="72" y="118" font-family="DejaVu Sans, sans-serif" font-size="14" fill="#25374f">Has an exact EXP-ID pointer</text>
<rect x="295" y="106" width="13" height="13" fill="#dce3ec"/>
<text x="317" y="118" font-family="DejaVu Sans, sans-serif" font-size="14" fill="#25374f">No exact pointer in this scan</text>

<text x="50" y="170" font-family="DejaVu Sans, sans-serif" font-size="18" fill="#18253b">Experiment IDs</text>
<rect x="{x}" y="146" width="{width}" height="42" fill="#dce3ec"/>
<rect x="{x}" y="146" width="{exp_width:.4f}" height="42" fill="#245eb4"/>
<text x="{x}" y="213" font-family="DejaVu Sans, sans-serif" font-size="16" fill="#18253b">{exp_linked:,} / {exp_total:,} linked ({100*exp_linked/exp_total:.3f}%)</text>
<text x="{x}" y="234" font-family="DejaVu Sans, sans-serif" font-size="13" fill="#52627a">The blue sliver is proportional; {exp_total-exp_linked:,} IDs have no exact pointer.</text>

<text x="50" y="292" font-family="DejaVu Sans, sans-serif" font-size="18" fill="#18253b">Formal targets</text>
<rect x="{x}" y="268" width="{width}" height="42" fill="#dce3ec"/>
<rect x="{x}" y="268" width="{target_width:.4f}" height="42" fill="#245eb4"/>
<text x="{x}" y="335" font-family="DejaVu Sans, sans-serif" font-size="16" fill="#18253b">{target_linked:,} / {target_total:,} name an experiment ID ({100*target_linked/target_total:.1f}%)</text>

<line x1="50" y1="374" x2="950" y2="374" stroke="#ccd5e2"/>
<text x="50" y="402" font-family="DejaVu Sans, sans-serif" font-size="15" fill="#18253b">What this shows: source text and target specs contain an exact existing EXP-ID token.</text>
<text x="50" y="427" font-family="DejaVu Sans, sans-serif" font-size="15" fill="#a33226">What it cannot show: theorem fidelity, proof validity, run replay, or performance.</text>
<text x="50" y="452" font-family="DejaVu Sans, sans-serif" font-size="12" fill="#52627a">Source: inventory.json at commit {commit}; generated by tools/formal_pointer_inventory.py.</text>
</svg>
'''
(root / 'coverage.svg').write_text(svg)
print(root / 'coverage.svg')
