#!/usr/bin/env bash
# Install Research KB as an MCP server for every local agent client.
#
#   ./scripts/setup-mcp.sh                 # stdio, all clients, refresh now
#   ./scripts/setup-mcp.sh --watch         # + background freshness daemon
#   ./scripts/setup-mcp.sh --transport http --url https://kb.example.com
#
# The script is idempotent. It writes a sources registry only when one does not
# exist, never overwrites an edited registry, and backs up every client config
# before changing it.
set -euo pipefail

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
KB_DIR=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)
REPO_ROOT=$(CDPATH= cd -- "$KB_DIR/.." && pwd)

HOME_DIR=${RESEARCH_KB_HOME:-$HOME/.local/share/research-kb}
CONFIG=${RESEARCH_KB_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/research-kb/sources.toml}
CLIENTS=all
TRANSPORT=stdio
URL=""
INSTALL=1
REFRESH=1
UPDATE=0
WATCH=0
INTERVAL=${RESEARCH_KB_WATCH_INTERVAL:-60}
FORCE_CONFIG=0
PYTHON_BIN=${PYTHON:-python3}

usage() {
  cat <<'EOF'
usage: setup-mcp.sh [options]

  --home DIR            catalog/state directory (default ~/.local/share/research-kb)
  --config FILE         source registry (default ~/.config/research-kb/sources.toml)
  --clients LIST        all | comma list of claude,codex,opencode,delphi
  --transport MODE      stdio (default) or http
  --url URL             base URL for --transport http
  --watch               install a launchd/systemd user job that refreshes
  --interval SECONDS    watcher poll interval (default 60)
  --update-sources      fast-forward registered git checkouts before refresh
  --skip-install        reuse the existing .venv
  --skip-refresh        register clients without rebuilding the catalog
  --force-config        rewrite the source registry from detected roots
  -h, --help            this text

Source roots can be overridden without editing the registry:
  RESEARCH_KB_SOURCE_CRYPTO_AUTORESEARCHER=/path/to/repo
  RESEARCH_KB_SOURCE_CRYPTO=/path/to/crypto
  RESEARCH_KB_SOURCE_CRYPTANALYSIS=/path/to/cryptanalysis
  RESEARCH_KB_SOURCE_CRYPTO_LEAN=/path/to/crypto-lean
  RESEARCH_KB_SOURCE_CRYPTOLOGIC_ARCHIVES=/path/to/archives
EOF
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --home) HOME_DIR=$2; shift 2 ;;
    --config) CONFIG=$2; shift 2 ;;
    --clients) CLIENTS=$2; shift 2 ;;
    --transport) TRANSPORT=$2; shift 2 ;;
    --url) URL=$2; shift 2 ;;
    --watch) WATCH=1; shift ;;
    --interval) INTERVAL=$2; shift 2 ;;
    --update-sources) UPDATE=1; shift ;;
    --skip-install) INSTALL=0; shift ;;
    --skip-refresh) REFRESH=0; shift ;;
    --force-config) FORCE_CONFIG=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

case "$TRANSPORT" in stdio|http) ;; *) echo "--transport must be stdio or http" >&2; exit 2 ;; esac
if [ "$TRANSPORT" = http ] && [ -z "$URL" ]; then
  echo "--transport http requires --url" >&2
  exit 2
fi

if [ "$INSTALL" = 1 ]; then
  if command -v uv >/dev/null 2>&1; then
    [ -x "$KB_DIR/.venv/bin/python" ] || uv venv --python 3.12 "$KB_DIR/.venv"
    uv pip install --python "$KB_DIR/.venv/bin/python" -e "$KB_DIR[index,pdf]"
  else
    [ -x "$KB_DIR/.venv/bin/python" ] || "$PYTHON_BIN" -m venv "$KB_DIR/.venv"
    "$KB_DIR/.venv/bin/python" -m pip install --upgrade pip >/dev/null
    "$KB_DIR/.venv/bin/python" -m pip install -e "$KB_DIR[index,pdf]"
  fi
fi

KB_BIN="$KB_DIR/.venv/bin/research-kb"
if [ ! -x "$KB_BIN" ]; then
  echo "error: $KB_BIN is missing; run without --skip-install" >&2
  exit 1
fi

export RESEARCH_KB_HOME="$HOME_DIR"
export RESEARCH_KB_CONFIG="$CONFIG"

detect_root() {
  local override=$1
  shift
  if [ -n "${override:-}" ] && [ -d "$override" ]; then
    (CDPATH= cd -- "$override" && pwd)
    return 0
  fi
  local candidate
  for candidate in "$@"; do
    if [ -d "$candidate" ]; then
      (CDPATH= cd -- "$candidate" && pwd)
      return 0
    fi
  done
  return 1
}

if [ "$FORCE_CONFIG" = 1 ] || [ ! -f "$CONFIG" ]; then
  mkdir -p "$(dirname "$CONFIG")"
  # research-kb may be a standalone checkout beside the research repos, or a
  # directory inside one. Only treat the parent as a source when it actually
  # looks like the crypto-autoresearcher corpus.
  SELF_SOURCE=""
  if [ -d "$REPO_ROOT/knowledge" ] && [ -d "$REPO_ROOT/ledger" ]; then
    SELF_SOURCE="$REPO_ROOT"
  fi
  {
    echo "# Generated by research-kb/scripts/setup-mcp.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
    echo "# Paths are absolute so the registry does not depend on the caller's cwd."
    echo "# Edit this file to add or remove a repository, then run: research-kb refresh"
    echo
    if root=$(detect_root "${RESEARCH_KB_SOURCE_CRYPTO_AUTORESEARCHER:-}" "$SELF_SOURCE" "$REPO_ROOT/../crypto-autoresearcher"); then
      cat <<EOF
[[sources]]
name = "crypto-autoresearcher"
root = "$root"
include = ["knowledge/**/*.md", "knowledge/leads/**/*.yaml", "knowledge/frontiers/**/*.yaml", "knowledge/derivations/**/*.py", "ledger/evidence/**/*.yaml", "ledger/hypotheses/**/*.yaml", "ledger/proposals/**/*.yaml", "ledger/questions/**/*.yaml", "ledger/decisions/**/*.yaml", "experiments/*/specification.yaml", "experiments/*/analysis.md", "docs/*.md", "inputs/*/paper_fulltext.md", "formal/**/*.lean"]
exclude = [".git/**", ".venv/**", "__pycache__/**", "**/archives/**"]

EOF
    else
      echo "# crypto-autoresearcher: not found; set RESEARCH_KB_SOURCE_CRYPTO_AUTORESEARCHER" >&2
    fi
    if root=$(detect_root "${RESEARCH_KB_SOURCE_CRYPTO:-}" "$REPO_ROOT/../crypto" "/Volumes/SSD990-2/crypto"); then
      cat <<EOF
[[sources]]
name = "crypto"
root = "$root"
include = ["research/notes/**/*.md", "papers/**/*.tex", "papers/**/*.md", "docs/**/*.md"]
exclude = [".git/**", ".lake/**", ".venv/**", "build/**", "**/archives/**"]

EOF
    else
      echo "# crypto: not found; set RESEARCH_KB_SOURCE_CRYPTO" >&2
    fi
    if root=$(detect_root "${RESEARCH_KB_SOURCE_CRYPTANALYSIS:-}" "$REPO_ROOT/../cryptanalysis" "/Volumes/SSD990-2/cryptanalysis"); then
      cat <<EOF
[[sources]]
name = "cryptanalysis"
root = "$root"
include = ["research/**/*.md", "papers/**/*.tex", "papers/**/*.md", "docs/**/*.md"]
exclude = [".git/**", ".lake/**", ".venv/**", "build/**", "**/archives/**"]

EOF
    else
      echo "# cryptanalysis: not found; set RESEARCH_KB_SOURCE_CRYPTANALYSIS" >&2
    fi
    if root=$(detect_root "${RESEARCH_KB_SOURCE_CRYPTO_LEAN:-}" "$REPO_ROOT/../crypto-lean" "/Volumes/SSD990-2/companion-repos/crypto-lean"); then
      cat <<EOF
[[sources]]
name = "crypto-lean"
root = "$root"
include = ["CryptoLean/**/*.lean", "CryptoLeanCore/**/*.lean"]
exclude = [".git/**", ".lake/**", ".venv/**", "build/**"]

EOF
    else
      echo "# crypto-lean: not found; set RESEARCH_KB_SOURCE_CRYPTO_LEAN" >&2
    fi
    if root=$(detect_root "${RESEARCH_KB_SOURCE_CRYPTOLOGIC_ARCHIVES:-}" "$REPO_ROOT/../cryptologic-archives"); then
      cat <<EOF
[[sources]]
name = "cryptologic-archives"
root = "$root"
include = ["docs/**/*.md", "profiles/**/*.md", "sources/originals/*.pdf", "sources/originals/*.txt", "data/*.json"]
exclude = [".git/**", "**/archives/**"]

EOF
    fi
  } > "$CONFIG"
  echo "wrote $CONFIG"
else
  echo "using existing $CONFIG (pass --force-config to regenerate)"
fi

if [ "$UPDATE" = 1 ]; then
  echo "fast-forwarding registered source checkouts ..."
  "$KB_BIN" update-sources || echo "warning: some sources did not fast-forward; continuing with the local revision" >&2
fi

if [ "$REFRESH" = 1 ]; then
  echo "refreshing catalog in $HOME_DIR ..."
  "$KB_BIN" refresh
fi

INSTALL_ARGS=(install-client --client "$CLIENTS" --transport "$TRANSPORT" --command "$KB_BIN")
if [ -n "$URL" ]; then
  INSTALL_ARGS+=(--url "$URL")
fi
"$KB_BIN" "${INSTALL_ARGS[@]}"

if [ "$WATCH" = 1 ]; then
  if [ "$(uname -s)" = Darwin ]; then
    PLIST="$HOME/Library/LaunchAgents/com.isogeny.research-kb-watch.plist"
    mkdir -p "$(dirname "$PLIST")" "$HOME/Library/Logs"
    cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>com.isogeny.research-kb-watch</string>
  <key>ProgramArguments</key>
  <array>
    <string>$KB_BIN</string><string>watch</string><string>--interval</string><string>$INTERVAL</string><string>--pull</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>RESEARCH_KB_HOME</key><string>$HOME_DIR</string>
    <key>RESEARCH_KB_CONFIG</key><string>$CONFIG</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/research-kb-watch.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/research-kb-watch.err.log</string>
</dict>
</plist>
EOF
    launchctl unload "$PLIST" 2>/dev/null || true
    launchctl load "$PLIST"
    echo "watcher loaded: $PLIST (every ${INTERVAL}s; log: ~/Library/Logs/research-kb-watch.log)"
  elif command -v systemctl >/dev/null 2>&1; then
    UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
    mkdir -p "$UNIT_DIR"
    cat > "$UNIT_DIR/research-kb-watch.service" <<EOF
[Unit]
Description=Research KB freshness watcher

[Service]
ExecStart=$KB_BIN watch --interval $INTERVAL --pull
Environment=RESEARCH_KB_HOME=$HOME_DIR
Environment=RESEARCH_KB_CONFIG=$CONFIG
Restart=always

[Install]
WantedBy=default.target
EOF
    systemctl --user daemon-reload
    systemctl --user enable --now research-kb-watch.service
    echo "watcher enabled: research-kb-watch.service"
  else
    echo "no launchd/systemd; add this to cron:" >&2
    echo "  */5 * * * * RESEARCH_KB_HOME='$HOME_DIR' RESEARCH_KB_CONFIG='$CONFIG' '$KB_BIN' watch --once --pull" >&2
  fi
fi

echo
"$KB_BIN" status
echo
echo "Clients registered: $CLIENTS ($TRANSPORT)."
echo "Verify with: $KB_BIN search 'KN-FIND' --top-k 1"
if [ "$TRANSPORT" = http ]; then
  echo "HTTP server: $KB_BIN serve   # requires RESEARCH_KB_AUTH_FILE"
else
  echo "Start the server on demand with: $KB_BIN mcp"
fi
echo "Delphi: delphi-kb 'question' prints context; delphi-kb-ask 'question' sends it to delphi ask."
